/**
 * PaperPositions entity — isolated paper-trading mirror of the Positions table.
 *
 * Stored in `paper_positions` to guarantee zero overlap with the live
 * `positions` table (Requirement 10.1: no shared database tables between
 * PaperEngine and LiveEngine).
 *
 * MFE (Maximum Favorable Excursion) and MAE (Maximum Adverse Excursion) are
 * updated continuously by PaperTradingService from simulated tick data.
 *
 * Requirements: 10.1
 */

import {
  Entity,
  PrimaryGeneratedColumn,
  Column,
  CreateDateColumn,
  UpdateDateColumn,
  Index,
  OneToMany,
} from 'typeorm';
import { PaperTrade } from './paper-trades.entity';

/** Position direction — determines SL monotonicity direction. */
export type PaperDirection = 'LONG' | 'SHORT';

@Entity('paper_positions')
@Index('idx_paper_positions_is_open', ['is_open'])
@Index('idx_paper_positions_instrument_is_open', ['instrument_id', 'is_open'])
export class PaperPosition {
  /** UUID primary key — generated by TypeORM (uuid v4). */
  @PrimaryGeneratedColumn('uuid')
  id!: string;

  /**
   * Engine identifier — always 'PAPER' for this table.
   * Retained to mirror the Positions schema.
   */
  @Column({ type: 'varchar', length: 10, default: 'PAPER' })
  engine!: string;

  /** FK → instruments.id — the instrument held. */
  @Column({ name: 'instrument_id', type: 'uuid' })
  instrument_id!: string;

  /**
   * FK → signals.id — the signal that initiated this paper position.
   * NULL for paper positions opened without a scored signal.
   */
  @Column({ name: 'signal_id', type: 'uuid', nullable: true })
  signal_id!: string | null;

  /** Trade direction; determines SL monotonicity rules. */
  @Column({ type: 'varchar', length: 5 })
  direction!: PaperDirection;

  /** Current open quantity (decreases on partial exits). */
  @Column({ type: 'integer' })
  quantity!: number;

  /**
   * Volume-weighted average price of all entry executions (NUMERIC 12,2).
   * Recalculated on each additional entry for scaled-in positions.
   */
  @Column({ name: 'average_entry_price', type: 'numeric', precision: 12, scale: 2 })
  average_entry_price!: string;

  /**
   * Active stop-loss level (NUMERIC 12,2).
   * Monotonically moves in the profit direction only.
   * NULL until a stop-loss is configured.
   */
  @Column({ name: 'current_sl', type: 'numeric', precision: 12, scale: 2, nullable: true })
  current_sl!: string | null;

  /**
   * Target price for this position leg (NUMERIC 12,2).
   * NULL when the strategy has no fixed target.
   */
  @Column({ name: 'target_price', type: 'numeric', precision: 12, scale: 2, nullable: true })
  target_price!: string | null;

  /**
   * Name of the active trailing stop mechanism.
   * NULL before a trailing stop is activated.
   */
  @Column({ name: 'trailing_stop_mechanism', type: 'varchar', nullable: true })
  trailing_stop_mechanism!: string | null;

  /**
   * Real-time unrealized P&L computed from simulated mark price (NUMERIC 15,2).
   * Continuously updated by PaperTradingService.
   */
  @Column({
    name: 'unrealized_pnl',
    type: 'numeric',
    precision: 15,
    scale: 2,
    default: '0',
  })
  unrealized_pnl!: string;

  /**
   * Maximum Favorable Excursion — highest unrealized P&L reached since entry
   * (NUMERIC 15,2). Updated only when current unrealized_pnl > stored mfe.
   */
  @Column({ type: 'numeric', precision: 15, scale: 2, default: '0' })
  mfe!: string;

  /**
   * Maximum Adverse Excursion — most negative unrealized P&L reached since entry
   * (NUMERIC 15,2). Updated only when current unrealized_pnl < stored mae.
   */
  @Column({ type: 'numeric', precision: 15, scale: 2, default: '0' })
  mae!: string;

  /** UTC timestamp when the first entry execution was confirmed. */
  @Column({ name: 'opened_at', type: 'timestamptz' })
  opened_at!: Date;

  /**
   * UTC timestamp when the position was fully closed.
   * NULL for open positions.
   */
  @Column({ name: 'closed_at', type: 'timestamptz', nullable: true })
  closed_at!: Date | null;

  /**
   * Boolean flag for fast open-position queries.
   * Set to `false` by PaperTradingService when quantity reaches 0.
   */
  @Column({ name: 'is_open', type: 'boolean', default: true })
  is_open!: boolean;

  /** UTC timestamp when the row was first inserted. */
  @CreateDateColumn({ name: 'created_at', type: 'timestamptz' })
  created_at!: Date;

  /** UTC timestamp of the most recent update to this row. */
  @UpdateDateColumn({ name: 'updated_at', type: 'timestamptz' })
  updated_at!: Date;

  // ── Relations ──────────────────────────────────────────────────────────────

  /**
   * Completed paper trade records derived from this position.
   * Inverse side of PaperTrade.position.
   */
  @OneToMany(() => PaperTrade, (trade) => trade.position)
  trades!: PaperTrade[];
}
