/**
 * Strategies entity — configuration table for the 8 trading strategies (A–H).
 *
 * Each strategy has an immutable code ('A' | 'B' | … | 'H') and a mutable
 * set of runtime configuration values that control eligibility, limits, and
 * performance gate thresholds.
 *
 * `compatible_regimes` is stored as a native PostgreSQL TEXT[] array so that
 * the application can query "strategies compatible with the current regime"
 * without deserialising JSON.
 *
 * `!` definite-assignment assertions are used on all ORM-populated properties
 * because TypeORM hydrates instances at runtime, not via constructors.
 *
 * Requirements: 18.1
 */

import {
  Column,
  CreateDateColumn,
  Entity,
  PrimaryGeneratedColumn,
  UpdateDateColumn,
} from 'typeorm';

/** Single-letter strategy code. Immutable after insert. */
export type StrategyCode = 'A' | 'B' | 'C' | 'D' | 'E' | 'F' | 'G' | 'H';

@Entity('strategies')
export class Strategies {
  /** UUID primary key — generated by TypeORM (uuid v4). */
  @PrimaryGeneratedColumn('uuid')
  id!: string;

  /**
   * Single-letter strategy code — unique, immutable after insert.
   * Valid values: 'A' | 'B' | 'C' | 'D' | 'E' | 'F' | 'G' | 'H'
   */
  @Column({ type: 'varchar', unique: true })
  code!: StrategyCode;

  /** Full human-readable strategy name. */
  @Column({ type: 'varchar' })
  name!: string;

  /** Whether the strategy is enabled for signal generation. */
  @Column({ type: 'boolean', name: 'is_active', default: true })
  isActive!: boolean;

  /**
   * Emergency suspension flag — set by RiskEngine on consecutive loss events.
   * A suspended strategy is excluded from live evaluation even if isActive=true.
   */
  @Column({ type: 'boolean', name: 'is_suspended', default: false })
  isSuspended!: boolean;

  /**
   * PostgreSQL TEXT[] — list of regime codes under which this strategy may
   * produce signals (e.g. ['TRENDING_BULLISH', 'BREAKOUT']).
   */
  @Column({ type: 'text', array: true, name: 'compatible_regimes' })
  compatibleRegimes!: string[];

  /**
   * Minimum required Risk:Reward ratio before a signal is forwarded.
   * NUMERIC(4,2) — returned as string by pg to preserve precision.
   */
  @Column({ type: 'numeric', precision: 4, scale: 2, name: 'min_rr_ratio' })
  minRrRatio!: string;

  /** Hard cap on simultaneously open positions for this strategy. */
  @Column({ type: 'integer', name: 'max_concurrent_positions' })
  maxConcurrentPositions!: number;

  /**
   * When true the strategy is permitted to generate signals during the
   * 09:15–09:20 opening volatility phase.
   */
  @Column({ type: 'boolean', name: 'opening_phase_compatible', default: false })
  openingPhaseCompatible!: boolean;

  /**
   * Minimum out-of-sample win-rate threshold required to remain active (0–100).
   * NULL means no threshold has been configured (new strategies in validation).
   */
  @Column({
    type: 'numeric',
    precision: 5,
    scale: 2,
    name: 'min_performance_threshold',
    nullable: true,
  })
  minPerformanceThreshold!: string | null;

  /**
   * Most-recently computed out-of-sample win rate (0.00 – 100.00).
   * NULL until the first back-test cycle completes.
   */
  @Column({
    type: 'numeric',
    precision: 5,
    scale: 2,
    name: 'current_oos_win_rate',
    nullable: true,
  })
  currentOosWinRate!: string | null;

  /**
   * Strategy-specific price deviation threshold expressed as a decimal fraction
   * (e.g. 0.005 = 0.5%).  When the entry price of an active signal deviates from
   * the current market price by more than this fraction before order submission,
   * the SignalScorer recomputes the composite score and re-validates it against
   * the 80-point threshold (Req 8.6).
   *
   * NULL means the strategy has not configured a custom threshold; the
   * SignalScoringService will fall back to its own default (0.005 = 0.5%).
   */
  @Column({
    type: 'numeric',
    precision: 6,
    scale: 4,
    name: 'price_deviation_threshold',
    nullable: true,
  })
  priceDeviationThreshold!: string | null;

  /**
   * Maximum number of seconds a generated signal remains valid before it is
   * automatically marked as "expired" if not acted upon (Req 8.7).
   *
   * NULL means the strategy has not configured a custom validity window; the
   * SignalScoringService will fall back to its own default (300 s = 5 minutes).
   */
  @Column({
    type: 'integer',
    name: 'max_validity_duration_seconds',
    nullable: true,
  })
  maxValidityDurationSeconds!: number | null;

  /**
   * When the strategy is suspended by the ComplianceModule, this field stores
   * the name of the failing compliance gate (e.g. 'POSITIVE_EXPECTANCY').
   * NULL when the strategy has never been suspended for a compliance failure.
   *
   * Requirements: 15.5
   */
  @Column({ type: 'varchar', nullable: true, name: 'suspension_reason' })
  suspensionReason!: string | null;

  /**
   * The computed value associated with the failing compliance gate at the time
   * of suspension (e.g. expectancy = -0.5, drawdown = 0.35, tradeCount = 25).
   * Stored as NUMERIC(15,6) to accommodate ratios, percentages, and counts.
   * NULL when the strategy has never been suspended for a compliance failure.
   *
   * Requirements: 15.5
   */
  @Column({
    type: 'numeric',
    precision: 15,
    scale: 6,
    nullable: true,
    name: 'failing_gate_value',
  })
  failingGateValue!: string | null;

  /**
   * Monotonically incrementing config version; bumped whenever a
   * StrategyVersions snapshot is created.
   */
  @Column({ type: 'integer', default: 1 })
  version!: number;

  /** Row creation timestamp (UTC). */
  @CreateDateColumn({ type: 'timestamptz', name: 'created_at' })
  createdAt!: Date;

  /** Last modification timestamp (UTC). */
  @UpdateDateColumn({ type: 'timestamptz', name: 'updated_at' })
  updatedAt!: Date;
}
