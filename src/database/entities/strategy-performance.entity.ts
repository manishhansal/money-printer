/**
 * StrategyPerformance entity — per-strategy daily performance record.
 *
 * Tracks trade outcome statistics and net P&L for each strategy, segmented by
 * trading date, engine, and optionally by market regime.  Used by the
 * AnalyticsService to evaluate strategy-level quality and by the SignalScorer
 * to weight selection rationale against historical out-of-sample win rates.
 *
 * FK note: strategy_id references the Strategies table (implemented in task 2.3).
 * The @ManyToOne relation will be wired once that entity exists; until then the
 * column is a bare UUID so migrations can create the FK constraint independently.
 *
 * Requirements: 18.1, 18.2
 *
 * NUMERIC columns are typed as `string` because PostgreSQL NUMERIC can exceed
 * IEEE-754 double precision; TypeORM/pg returns them as strings by default.
 */

import {
  Entity,
  PrimaryGeneratedColumn,
  Column,
  CreateDateColumn,
  UpdateDateColumn,
  Index,
} from 'typeorm';

import { EngineType } from './capital-ledgers.entity';

@Entity('strategy_performance')
@Index('idx_strategy_performance_strategy_engine_date', ['strategy_id', 'engine', 'trading_date'])
export class StrategyPerformance {
  /** Surrogate UUID primary key — generated by TypeORM via the `uuid` package. */
  @PrimaryGeneratedColumn('uuid')
  id!: string;

  /**
   * Strategy whose performance this row records.
   * FK → Strategies(id) — constraint added in migration once Strategies table exists.
   */
  @Column({ type: 'uuid' })
  strategy_id!: string;

  /** Trading engine context for this performance record. */
  @Column({ type: 'varchar', length: 10 })
  engine!: EngineType;

  /**
   * Market regime label active during this trading date
   * (e.g. "TRENDING_BULLISH", "HIGH_VIX_RANGE_BOUND").
   * NULL when regime-level segmentation is not applicable.
   */
  @Column({ type: 'varchar', length: 50, nullable: true })
  regime!: string | null;

  /**
   * NSE calendar date this record covers.
   * Stored as PostgreSQL DATE; TypeORM returns it as a JS string 'YYYY-MM-DD'.
   */
  @Column({ type: 'date' })
  trading_date!: string;

  /** Total trades attributed to this strategy on this date. */
  @Column({ type: 'int', default: 0 })
  trades_count!: number;

  /** Number of trades that closed with a positive net P&L. */
  @Column({ type: 'int', default: 0 })
  win_count!: number;

  /** Number of trades that closed with a negative net P&L. */
  @Column({ type: 'int', default: 0 })
  loss_count!: number;

  /**
   * Aggregate net P&L (after charges) for this strategy on this date.
   * Stored as NUMERIC(15,2); TypeORM returns PostgreSQL NUMERIC as a string.
   */
  @Column({ type: 'decimal', precision: 15, scale: 2, default: '0.00' })
  total_net_pnl!: string;

  /**
   * Free-text capture of why this strategy was selected for trading on this date
   * (regime match, signal quality, historical performance, etc.).
   */
  @Column({ type: 'text', nullable: true })
  selection_rationale!: string | null;

  /**
   * Out-of-sample win rate used as input for strategy scoring on this date.
   * Expressed as a percentage (0.00–100.00).
   * NULL if no out-of-sample validation data was available.
   */
  @Column({ type: 'decimal', precision: 5, scale: 2, nullable: true })
  oos_win_rate!: string | null;

  /** Row creation timestamp (UTC); set once by the database on INSERT. */
  @CreateDateColumn({ type: 'timestamptz' })
  created_at!: Date;

  /** Last update timestamp (UTC); automatically refreshed on every UPDATE. */
  @UpdateDateColumn({ type: 'timestamptz' })
  updated_at!: Date;
}
