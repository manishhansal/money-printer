/**
 * BrokerAccounts entity — stores Dhan brokerage account credentials.
 *
 * Sensitive credential columns (`api_key`, `access_token`) are encrypted at
 * rest using AES-256-GCM via `EncryptedColumnTransformer`.
 *
 * The `!` definite assignment assertions tell TypeScript that TypeORM will
 * populate these properties at runtime (via hydration), not the constructor.
 *
 * Requirements: 16.8 (field-level encryption), 18.1
 */

import {
  Column,
  CreateDateColumn,
  Entity,
  Index,
  PrimaryGeneratedColumn,
  UpdateDateColumn,
} from 'typeorm';
import { encryptedColumnTransformer } from '../../common/transformers/encrypted-column.transformer';

@Entity({ name: 'broker_accounts' })
@Index(['userId', 'broker'])
export class BrokerAccounts {
  /** UUID primary key — generated by TypeORM (uuid package). */
  @PrimaryGeneratedColumn('uuid')
  id!: string;

  /** Application user that owns this broker account. */
  @Column({ name: 'user_id', type: 'varchar' })
  userId!: string;

  /**
   * Broker identifier.  Defaults to 'DHAN' as Dhan/DhanHQ is the exclusive
   * supported broker for MoneyPrinter.
   */
  @Column({ name: 'broker', type: 'varchar', default: 'DHAN' })
  broker!: string;

  /**
   * Broker-assigned client / account identifier (e.g. Dhan client ID).
   * Not treated as a secret on its own, but combined with api_key it
   * constitutes access credentials.
   */
  @Column({ name: 'client_id', type: 'varchar' })
  clientId!: string;

  /**
   * Dhan API key — ENCRYPTED at rest with AES-256-GCM.
   * The transformer's `to()` method encrypts on write; `from()` decrypts on
   * read.  The plaintext value is never persisted to the database.
   *
   * Requirements: 16.8
   */
  @Column({
    name: 'api_key',
    type: 'varchar',
    transformer: encryptedColumnTransformer,
  })
  apiKey!: string;

  /**
   * Dhan access token — ENCRYPTED at rest with AES-256-GCM.
   *
   * Requirements: 16.8
   */
  @Column({
    name: 'access_token',
    type: 'varchar',
    transformer: encryptedColumnTransformer,
  })
  accessToken!: string;

  /** Whether this account is currently active and eligible for trading. */
  @Column({ name: 'is_active', type: 'boolean', default: false })
  isActive!: boolean;

  /**
   * Static egress IP address associated with this account.
   * Dhan requires API calls to originate from a whitelisted static IP.
   * Nullable — may be null during onboarding before IP registration.
   */
  @Column({ name: 'static_ip', type: 'varchar', nullable: true })
  staticIp!: string | null;

  /** Row creation timestamp (UTC). */
  @CreateDateColumn({
    name: 'created_at',
    type: 'timestamp with time zone',
  })
  createdAt!: Date;

  /** Last modification timestamp (UTC). */
  @UpdateDateColumn({
    name: 'updated_at',
    type: 'timestamp with time zone',
  })
  updatedAt!: Date;
}
