/**
 * Instruments entity — master catalogue of NSE F&O instruments.
 *
 * Populated and maintained by InstrumentDiscovery.  Underlying indices are
 * stored here too but are classified separately (`instrument_type = 'INDEX'`)
 * and are NEVER submitted to the ExecutionService as trade targets.
 *
 * Composite indexes:
 *   1. (underlying, expiry_date, option_type) — option chain / expiry lookups
 *   2. (is_active, liquidity_score DESC)       — active-universe ranking queries
 *
 * The `!` definite assignment assertions tell TypeScript that TypeORM will
 * populate these properties at runtime (via hydration), not the constructor.
 *
 * Requirements: 4.1, 4.2, 18.1
 */

import {
  Column,
  CreateDateColumn,
  Entity,
  Index,
  PrimaryGeneratedColumn,
  UpdateDateColumn,
} from 'typeorm';

/**
 * Supported instrument types.
 * `INDEX` instruments are used for directional signal computation only and
 * must NEVER be forwarded to the ExecutionService (Requirement 4.6).
 */
export type InstrumentType =
  'INDEX_OPTION' | 'STOCK_OPTION' | 'INDEX_FUTURE' | 'STOCK_FUTURE' | 'INDEX';

/** Option type — relevant only for options contracts. */
export type OptionType = 'CE' | 'PE';

@Entity({ name: 'instruments' })
// Index 1 — option chain queries: filter by underlying & expiry, then option type
@Index('idx_instruments_underlying_expiry_option_type', ['underlying', 'expiryDate', 'optionType'])
// Index 2 — active-universe ranking: active instruments sorted by descending liquidity.
// The DESC sort on liquidity_score is defined in the migration; here we register the
// index name so TypeORM can reference it. The column ordering (is_active first) allows
// the planner to use an index scan for active=true + ORDER BY liquidity_score DESC.
@Index('idx_instruments_is_active_liquidity_score', ['isActive', 'liquidityScore'])
export class Instruments {
  /** UUID primary key — generated by TypeORM (uuid package). */
  @PrimaryGeneratedColumn('uuid')
  id!: string;

  /**
   * Dhan security ID — the broker-assigned unique instrument identifier.
   * Used when subscribing to market data feeds and placing orders.
   */
  @Column({ name: 'security_id', type: 'varchar', unique: true })
  securityId!: string;

  /** Exchange trading symbol (e.g. "NIFTY24JAN21000CE"). */
  @Column({ name: 'trading_symbol', type: 'varchar' })
  tradingSymbol!: string;

  /**
   * Exchange on which the instrument is listed.
   * For NSE F&O instruments this is always "NSE".
   */
  @Column({ name: 'exchange', type: 'varchar' })
  exchange!: string;

  /**
   * Market segment identifier (e.g. "FO", "IDX_I").
   * Used to determine the correct Dhan API segment parameter.
   */
  @Column({ name: 'segment', type: 'varchar' })
  segment!: string;

  /**
   * Instrument classification.
   * Drives InstrumentDiscovery routing logic — only 'INDEX_OPTION',
   * 'STOCK_OPTION', 'INDEX_FUTURE', and 'STOCK_FUTURE' are tradable.
   * 'INDEX' instruments are used solely for regime and signal computation.
   */
  @Column({ name: 'instrument_type', type: 'varchar' })
  instrumentType!: InstrumentType;

  /**
   * Underlying index or stock symbol (e.g. "NIFTY", "BANKNIFTY").
   * Part of composite index 1 for fast option chain lookups.
   */
  @Column({ name: 'underlying', type: 'varchar' })
  underlying!: string;

  /**
   * Contract expiry date (for futures and options).
   * NULL for underlying index instruments.
   * Part of composite index 1.
   */
  @Column({ name: 'expiry_date', type: 'date', nullable: true })
  expiryDate!: string | null;

  /**
   * Strike price (INR) — NUMERIC(10,2) to avoid float precision loss.
   * TypeORM/pg returns NUMERIC as a string; callers must parse with Decimal.js
   * or similar for arithmetic.
   * NULL for underlying index instruments and futures.
   */
  @Column({
    name: 'strike_price',
    type: 'numeric',
    precision: 10,
    scale: 2,
    nullable: true,
  })
  strikePrice!: string | null;

  /**
   * Option type — 'CE' (Call) or 'PE' (Put).
   * NULL for non-option instruments (futures, indices).
   * Part of composite index 1.
   */
  @Column({ name: 'option_type', type: 'varchar', nullable: true })
  optionType!: OptionType | null;

  /**
   * Number of units per lot (exchange-defined).
   * Used in position sizing by the RiskEngine.
   * A zero or missing value causes the RiskEngine to reject the signal
   * (Requirement 9.11).
   */
  @Column({ name: 'lot_size', type: 'integer' })
  lotSize!: number;

  /**
   * Minimum price movement (INR) — NUMERIC(10,4).
   * Used for order price validation and slippage estimation.
   */
  @Column({
    name: 'tick_size',
    type: 'numeric',
    precision: 10,
    scale: 4,
  })
  tickSize!: string;

  /**
   * Exchange-defined upper limit on order quantity per order.
   * Enforced by the ExecutionService before order submission.
   * NULL when not applicable or not yet fetched from the exchange.
   */
  @Column({ name: 'freeze_quantity', type: 'integer', nullable: true })
  freezeQuantity!: number | null;

  /**
   * Open interest — total number of outstanding contracts for this instrument.
   * Used by InstrumentDiscovery to enforce the minimum OI eligibility invariant
   * for STOCK_OPTION instruments (Requirement 4.8).
   * Updated during each instrument discovery scan.
   */
  @Column({ name: 'open_interest', type: 'integer', nullable: true, default: 0 })
  openInterest!: number;

  /**
   * Average daily volume — average number of contracts traded per day.
   * Used by InstrumentDiscovery to enforce the minimum ADV eligibility invariant
   * for STOCK_OPTION instruments (Requirement 4.8).
   * Updated during each instrument discovery scan.
   */
  @Column({ name: 'avg_daily_volume', type: 'integer', nullable: true, default: 0 })
  avgDailyVolume!: number;

  /**
   * Whether this instrument is currently in the active trading universe.
   * Set to `false` when liquidity score drops below the configured minimum.
   * Part of composite index 2.
   */
  @Column({ name: 'is_active', type: 'boolean', default: true })
  isActive!: boolean;

  /**
   * Composite liquidity score (0–100).
   * Computed by InstrumentDiscovery from volume, OI, bid-ask spread,
   * market depth, and best-bid/ask quantity (Requirement 4.2).
   * NUMERIC(5,2) supports values from 0.00 to 100.00.
   * Part of composite index 2 — migration defines DESC sort order.
   */
  @Column({
    name: 'liquidity_score',
    type: 'numeric',
    precision: 5,
    scale: 2,
    default: '0.00',
  })
  liquidityScore!: string;

  /**
   * Whether this instrument has been approved for order submission.
   * Only instruments that pass all eligibility checks (OI, ADV, score) AND
   * are classified as tradable (`instrumentType !== 'INDEX'`) may be set true.
   */
  @Column({ name: 'is_tradable', type: 'boolean', default: false })
  isTradable!: boolean;

  /**
   * UTC timestamp of the last InstrumentDiscovery scan that evaluated this
   * instrument.  NULL before any scan has run.
   */
  @Column({ name: 'last_scanned_at', type: 'timestamp with time zone', nullable: true })
  lastScannedAt!: Date | null;

  /** Row creation timestamp (UTC). */
  @CreateDateColumn({
    name: 'created_at',
    type: 'timestamp with time zone',
  })
  createdAt!: Date;

  /** Last modification timestamp (UTC). */
  @UpdateDateColumn({
    name: 'updated_at',
    type: 'timestamp with time zone',
  })
  updatedAt!: Date;
}
