/**
 * UserSettings entity — per-user application preferences and capital parameters.
 *
 * One row per registered user.  All timestamps are stored in UTC.
 * Financial values use NUMERIC to avoid floating-point precision loss.
 *
 * The `!` definite assignment assertions tell TypeScript that TypeORM will
 * populate these properties at runtime (via hydration), not the constructor.
 *
 * Requirements: 18.1
 */

import {
  Column,
  CreateDateColumn,
  Entity,
  PrimaryGeneratedColumn,
  UpdateDateColumn,
} from 'typeorm';

@Entity({ name: 'user_settings' })
export class UserSettings {
  /** UUID primary key — generated by TypeORM (uuid package). */
  @PrimaryGeneratedColumn('uuid')
  id!: string;

  /**
   * Reference to the application user.
   * Unique constraint ensures a single settings row per user.
   */
  @Column({ name: 'user_id', type: 'varchar', unique: true })
  userId!: string;

  /** UI theme preference (e.g. "dark", "light"). */
  @Column({ name: 'theme', type: 'varchar', default: 'dark' })
  theme!: string;

  /**
   * Percentage of Dynamic_Capital to risk per trade.
   * NUMERIC(5,4) — supports values like 1.5000 (%).
   * TypeORM/pg returns NUMERIC as a string to preserve precision.
   */
  @Column({
    name: 'default_risk_percentage',
    type: 'numeric',
    precision: 5,
    scale: 4,
    default: '1.0000',
  })
  defaultRiskPercentage!: string;

  /**
   * Maximum allowed intraday net loss as a percentage of capital.
   * NUMERIC(5,4).
   */
  @Column({
    name: 'max_daily_loss_percentage',
    type: 'numeric',
    precision: 5,
    scale: 4,
    default: '2.0000',
  })
  maxDailyLossPercentage!: string;

  /**
   * Starting capital for the paper trading engine (INR).
   * NUMERIC(15,2) supports values up to 9,999,999,999,999.99.
   */
  @Column({
    name: 'paper_starting_capital',
    type: 'numeric',
    precision: 15,
    scale: 2,
    default: '100000.00',
  })
  paperStartingCapital!: string;

  /**
   * Starting capital for the live trading engine (INR).
   * NUMERIC(15,2).
   */
  @Column({
    name: 'live_starting_capital',
    type: 'numeric',
    precision: 15,
    scale: 2,
    default: '0.00',
  })
  liveStartingCapital!: string;

  /** Whether push notifications to the Extension are enabled. */
  @Column({ name: 'notifications_enabled', type: 'boolean', default: true })
  notificationsEnabled!: boolean;

  /** Row creation timestamp (UTC). Set once by TypeORM on INSERT. */
  @CreateDateColumn({
    name: 'created_at',
    type: 'timestamp with time zone',
  })
  createdAt!: Date;

  /** Last modification timestamp (UTC). Updated by TypeORM on every UPDATE. */
  @UpdateDateColumn({
    name: 'updated_at',
    type: 'timestamp with time zone',
  })
  updatedAt!: Date;
}
