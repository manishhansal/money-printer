/**
 * RiskEvents entity — immutable audit log for every risk control activation.
 *
 * Captures all RiskEngine decisions: lockouts, halts, kill-switch activations,
 * order rejections, and informational metric breaches.  Rows are append-only and
 * are never modified or deleted after creation.
 *
 * FK notes:
 *   affected_instrument_id → Instruments(id)  (task 2.1)
 *   affected_strategy_id   → Strategies(id)   (task 2.3)
 * Both FK constraints are wired in migrations once the referenced tables exist.
 *
 * Requirements: 18.1, 18.2
 *
 * NUMERIC columns are typed as `string` because PostgreSQL NUMERIC can exceed
 * IEEE-754 double precision; TypeORM/pg returns them as strings by default.
 */

import { Entity, PrimaryGeneratedColumn, Column, CreateDateColumn, Index } from 'typeorm';

import { EngineType } from './capital-ledgers.entity';

/** All discrete risk event categories the RiskEngine can emit. */
export type RiskEventType =
  | 'TWO_LOSS_LOCKOUT'
  | 'EMERGENCY_HALT'
  | 'KILL_SWITCH'
  | 'SL_REJECTION'
  | 'DAILY_LOSS_LIMIT'
  | 'ZERO_PER_UNIT_RISK'
  | 'INVALID_LOT_SIZE'
  | 'STALE_DATA'
  | 'VIX_REDUCTION'
  | 'VIX_RESTORE'
  /** Session-mandated intraday square-off; recorded by LiveEngine at 15:15 IST. */
  | 'MANDATORY_EXIT';

@Entity('risk_events')
@Index('idx_risk_events_engine_event_type_occurred_at', ['engine', 'event_type', 'occurred_at'])
export class RiskEvents {
  /** Surrogate UUID primary key — generated by TypeORM via the `uuid` package. */
  @PrimaryGeneratedColumn('uuid')
  id!: string;

  /** Trading engine context in which the event occurred. */
  @Column({ type: 'varchar', length: 10 })
  engine!: EngineType;

  /** Specific risk control that was activated. */
  @Column({ type: 'varchar', length: 30 })
  event_type!: RiskEventType;

  /** Human-readable explanation of why the risk control was triggered. */
  @Column({ type: 'text' })
  reason!: string;

  /** Name of the metric that crossed a threshold (e.g. "daily_loss_pct"). */
  @Column({ type: 'varchar', length: 100, nullable: true })
  triggering_metric_name!: string | null;

  /**
   * Observed value of the triggering metric at the moment of activation.
   * Stored as NUMERIC(15,4) for high-precision metric values.
   */
  @Column({ type: 'decimal', precision: 15, scale: 4, nullable: true })
  triggering_metric_value!: string | null;

  /**
   * Configured threshold value that was breached to trigger this event.
   * Stored as NUMERIC(15,4) to match triggering_metric_value precision.
   */
  @Column({ type: 'decimal', precision: 15, scale: 4, nullable: true })
  threshold_value!: string | null;

  /**
   * Instrument affected by this risk event, if applicable.
   * FK → Instruments(id) — constraint added in migration once Instruments table exists.
   */
  @Column({ type: 'uuid', nullable: true })
  affected_instrument_id!: string | null;

  /**
   * Strategy affected by this risk event, if applicable.
   * FK → Strategies(id) — constraint added in migration once Strategies table exists.
   */
  @Column({ type: 'uuid', nullable: true })
  affected_strategy_id!: string | null;

  /**
   * Module or process that initiated the risk action
   * (e.g. "RiskEngine", "UserKillSwitch", "SessionManager").
   */
  @Column({ type: 'varchar', length: 100 })
  initiating_actor!: string;

  /** UTC timestamp when the risk event occurred. */
  @Column({ type: 'timestamptz' })
  occurred_at!: Date;

  /** Row creation timestamp (UTC); set once by the database on INSERT. */
  @CreateDateColumn({ type: 'timestamptz' })
  created_at!: Date;
}
