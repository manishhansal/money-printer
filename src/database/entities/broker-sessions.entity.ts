/**
 * BrokerSessions entity — active Dhan WebSocket / API session tokens.
 *
 * `session_token` is encrypted at rest using AES-256-GCM via
 * `EncryptedColumnTransformer`.  The plaintext token is never persisted.
 *
 * A session belongs to exactly one BrokerAccount and has a defined expiry.
 * Session management logic (creation, renewal, invalidation) lives in
 * DhanApiClient / SecretsService — not in this entity.
 *
 * The `!` definite assignment assertions tell TypeScript that TypeORM will
 * populate these properties at runtime (via hydration), not the constructor.
 *
 * Requirements: 16.8 (field-level encryption), 18.1
 */

import {
  Column,
  CreateDateColumn,
  Entity,
  Index,
  JoinColumn,
  ManyToOne,
  PrimaryGeneratedColumn,
  UpdateDateColumn,
} from 'typeorm';
import { encryptedColumnTransformer } from '../../common/transformers/encrypted-column.transformer';
import { BrokerAccounts } from './broker-accounts.entity';

@Entity({ name: 'broker_sessions' })
@Index(['brokerAccountId', 'isActive'])
export class BrokerSessions {
  /** UUID primary key — generated by TypeORM (uuid package). */
  @PrimaryGeneratedColumn('uuid')
  id!: string;

  /**
   * Foreign key → BrokerAccounts.id
   * Stored as a bare UUID column so that it remains queryable without a JOIN.
   */
  @Column({ name: 'broker_account_id', type: 'uuid' })
  brokerAccountId!: string;

  /**
   * The owning BrokerAccounts record.
   * Loaded lazily by default; use `relations` in queries when needed.
   */
  @ManyToOne(() => BrokerAccounts, { onDelete: 'CASCADE', nullable: false })
  @JoinColumn({ name: 'broker_account_id' })
  brokerAccount!: BrokerAccounts;

  /**
   * Dhan session token — ENCRYPTED at rest with AES-256-GCM.
   *
   * The transformer's `to()` method encrypts on write; `from()` decrypts on
   * read.  The plaintext token is never stored in the database.
   *
   * Requirements: 16.8, 3.3 (session token must not be persisted in plaintext)
   */
  @Column({
    name: 'session_token',
    type: 'varchar',
    transformer: encryptedColumnTransformer,
  })
  sessionToken!: string;

  /**
   * UTC timestamp at which this session token expires.
   * The DhanApiClient must not use a session whose `expiresAt` is in the past.
   */
  @Column({ name: 'expires_at', type: 'timestamp with time zone' })
  expiresAt!: Date;

  /**
   * Whether this session is currently valid and should be used for API calls.
   * Set to `false` on expiry, token invalidation, or explicit logout.
   */
  @Column({ name: 'is_active', type: 'boolean', default: true })
  isActive!: boolean;

  /** Row creation timestamp (UTC). */
  @CreateDateColumn({
    name: 'created_at',
    type: 'timestamp with time zone',
  })
  createdAt!: Date;

  /** Last modification timestamp (UTC). */
  @UpdateDateColumn({
    name: 'updated_at',
    type: 'timestamp with time zone',
  })
  updatedAt!: Date;
}
