/**
 * SignalEvaluations entity — audit log of every strategy evaluation cycle.
 *
 * A record is written for every evaluation regardless of whether a signal was
 * produced.  This lets the analysis layer distinguish between:
 *   - Evaluations that produced a signal  (producedSignal = true, signalId set)
 *   - Evaluations skipped with a reason   (skipReason populated)
 *
 * The composite index on (strategy_id, evaluated_at DESC) supports time-series
 * queries for strategy-level evaluation frequency and skip-rate metrics.
 *
 * `!` definite-assignment assertions are used on all ORM-populated properties
 * because TypeORM hydrates instances at runtime, not via constructors.
 *
 * Requirements: 18.1
 */

import {
  Column,
  Entity,
  Index,
  JoinColumn,
  ManyToOne,
  PrimaryGeneratedColumn,
  RelationId,
} from 'typeorm';
import { Signals } from './signals.entity';
import { Strategies } from './strategies.entity';

@Entity('signal_evaluations')
@Index('idx_signal_evaluations_strategy_evaluated_at', ['strategy', 'evaluatedAt'])
export class SignalEvaluations {
  /** UUID primary key — generated by TypeORM (uuid v4). */
  @PrimaryGeneratedColumn('uuid')
  id!: string;

  /** Strategy that performed this evaluation. */
  @ManyToOne(() => Strategies, { nullable: false, onDelete: 'CASCADE' })
  @JoinColumn({ name: 'strategy_id' })
  strategy!: Strategies;

  /**
   * Convenience read-only accessor for the strategy FK column value.
   * Populated by TypeORM from the strategy_id join column; not a separate DB column.
   */
  @RelationId((se: SignalEvaluations) => se.strategy)
  strategyId!: string;

  /**
   * FK → instruments.id — the instrument evaluated in this cycle.
   * Stored as a plain UUID column; a @ManyToOne relation is available via
   * the Instruments entity (instruments.entity.ts).
   */
  @Column({ type: 'uuid', name: 'instrument_id' })
  instrumentId!: string;

  /** UTC timestamp when the evaluation was performed. */
  @Column({ type: 'timestamptz', name: 'evaluated_at' })
  evaluatedAt!: Date;

  /** True when the evaluation resulted in a Signal record being emitted. */
  @Column({ type: 'boolean', name: 'produced_signal' })
  producedSignal!: boolean;

  /**
   * Reason the evaluation did not produce a signal.
   * Common values: "incompatible regime" | "regime unavailable" |
   *                "score below threshold" | "r:r below minimum" |
   *                "max concurrent positions reached"
   * NULL when producedSignal = true.
   */
  @Column({ type: 'varchar', name: 'skip_reason', nullable: true })
  skipReason!: string | null;

  /**
   * Link to the Signal record produced by this evaluation.
   * NULL when producedSignal = false.
   * ON DELETE SET NULL preserves this audit record even if the signal
   * is pruned by data-retention jobs.
   */
  @ManyToOne(() => Signals, { nullable: true, onDelete: 'SET NULL' })
  @JoinColumn({ name: 'signal_id' })
  signal!: Signals | null;

  /**
   * Convenience read-only accessor for the signal FK column value.
   * Populated by TypeORM from the signal_id join column; not a separate DB column.
   */
  @RelationId((se: SignalEvaluations) => se.signal)
  signalId!: string | null;

  /** Market regime code active at evaluation time (denormalised for fast filtering). */
  @Column({ type: 'varchar', name: 'regime_at_evaluation', nullable: true })
  regimeAtEvaluation!: string | null;
}
