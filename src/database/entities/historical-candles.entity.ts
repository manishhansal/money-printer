/**
 * HistoricalCandles entity — OHLCV candle data at multiple granularities
 * ingested from the Dhan historical candles API.
 *
 * Supported granularities and their retention policies:
 *   - "1m"  → 90 days
 *   - "5m"  → 90 days
 *   - "15m" → 1 year
 *   - "1d"  → 5 years
 *
 * The UNIQUE constraint on (instrument_id, granularity, timestamp) prevents
 * duplicate candle ingestion on re-fetch or reconnect.  The matching compound
 * index with timestamp DESC supports efficient "latest N candles" queries used
 * by TechnicalAnalysis indicators (VWAP, ATR, EMA, ORB, etc.).
 *
 * All price columns use NUMERIC to avoid floating-point precision loss.
 * Timestamps are stored in UTC (timestamp with time zone).
 *
 * The `!` definite assignment assertions tell TypeScript that TypeORM will
 * populate these properties at runtime (via hydration), not the constructor.
 *
 * Requirements: 18.1, 18.8
 */

import { Column, Entity, Index, PrimaryGeneratedColumn, Unique } from 'typeorm';

/**
 * Allowed candle granularity values.
 * Enforced at the application layer; the DB column is a plain varchar.
 */
export type CandleGranularity = '1m' | '5m' | '15m' | '1d';

/**
 * UNIQUE constraint: prevents duplicate candles for the same instrument,
 * granularity, and opening timestamp.
 *
 * SQL equivalent:
 *   ALTER TABLE historical_candles
 *     ADD CONSTRAINT "UQ_historical_candles_instrument_granularity_timestamp"
 *     UNIQUE (instrument_id, granularity, timestamp);
 */
@Entity({ name: 'historical_candles' })
@Unique('UQ_historical_candles_instrument_granularity_timestamp', [
  'instrumentId',
  'granularity',
  'timestamp',
])
/**
 * Compound index for fast "latest N candles for instrument + granularity"
 * lookups.
 * NOTE: The migration for this index MUST specify `timestamp DESC` to avoid
 * a sort step on the most common query pattern.
 *
 * SQL equivalent:
 *   CREATE INDEX "IDX_historical_candles_instrument_granularity_timestamp"
 *     ON historical_candles (instrument_id, granularity, timestamp DESC);
 */
@Index('IDX_historical_candles_instrument_granularity_timestamp', [
  'instrumentId',
  'granularity',
  'timestamp',
])
export class HistoricalCandles {
  /** UUID primary key — generated by TypeORM (uuid package). */
  @PrimaryGeneratedColumn('uuid')
  id!: string;

  /**
   * References the instrument this candle belongs to.
   * FK → instruments.id.
   *
   * Stored as a plain uuid column; the @ManyToOne relation is wired from
   * the Instruments entity side (task 2.1).
   */
  @Column({ name: 'instrument_id', type: 'uuid' })
  instrumentId!: string;

  /**
   * Candle aggregation period.
   * One of: "1m" | "5m" | "15m" | "1d".
   * Application code MUST validate against CandleGranularity before persisting.
   */
  @Column({ name: 'granularity', type: 'varchar', length: 4 })
  granularity!: CandleGranularity;

  /**
   * Opening price for the candle period.
   * NUMERIC(12,2) — supports up to ₹9,999,999,999.99.
   * TypeORM/pg returns NUMERIC as string; callers must parse for arithmetic.
   */
  @Column({ name: 'open_price', type: 'numeric', precision: 12, scale: 2 })
  openPrice!: string;

  /**
   * Highest price traded within the candle period.
   * NUMERIC(12,2).
   */
  @Column({ name: 'high_price', type: 'numeric', precision: 12, scale: 2 })
  highPrice!: string;

  /**
   * Lowest price traded within the candle period.
   * NUMERIC(12,2).
   */
  @Column({ name: 'low_price', type: 'numeric', precision: 12, scale: 2 })
  lowPrice!: string;

  /**
   * Closing price at the end of the candle period.
   * NUMERIC(12,2).
   */
  @Column({ name: 'close_price', type: 'numeric', precision: 12, scale: 2 })
  closePrice!: string;

  /**
   * Total volume traded within the candle period.
   * BIGINT — TypeORM returns bigint columns as string in JavaScript to
   * avoid 53-bit integer precision loss.
   */
  @Column({ name: 'volume', type: 'bigint' })
  volume!: string;

  /**
   * Open interest at the close of the candle period.
   * Nullable — not available for all instrument types (e.g. equities).
   * BIGINT returned as string.
   */
  @Column({ name: 'oi', type: 'bigint', nullable: true })
  oi!: string | null;

  /**
   * UTC timestamp marking the opening of this candle.
   * Part of the UNIQUE constraint and compound index (see class decorators).
   * Indexed in DESC order in migrations — see IDX_historical_candles_* above.
   */
  @Column({ name: 'timestamp', type: 'timestamp with time zone' })
  timestamp!: Date;
}
