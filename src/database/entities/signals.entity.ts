/**
 * Signals entity — one record per signal produced by the SignalScoring module.
 *
 * Every generated signal is persisted here regardless of whether it is
 * ultimately accepted, rejected, expired, or executed.  The 8 component
 * scores (score_*) and the raw `measured_inputs` JSONB provide full
 * reproducibility for back-testing and audit.
 *
 * Composite indexes support the two most common query patterns:
 *   1. Active/pending signals for a specific instrument (ExecutionService).
 *   2. Active/pending signals by engine (LIVE vs. PAPER reconciliation).
 *
 * NUMERIC columns are typed as `string` because PostgreSQL NUMERIC can exceed
 * IEEE-754 double precision; TypeORM/pg returns them as strings by default.
 *
 * `!` definite-assignment assertions are used on all ORM-populated properties
 * because TypeORM hydrates instances at runtime, not via constructors.
 *
 * Requirements: 18.1
 */

import {
  Column,
  CreateDateColumn,
  Entity,
  Index,
  JoinColumn,
  ManyToOne,
  PrimaryGeneratedColumn,
  RelationId,
} from 'typeorm';
import { Strategies } from './strategies.entity';

/** Trading engine context. */
export type SignalEngine = 'LIVE' | 'PAPER';

/** Trade direction. */
export type SignalDirection = 'BUY' | 'SELL';

/** Signal lifecycle status. */
export type SignalStatus = 'active' | 'accepted' | 'rejected' | 'expired' | 'executed';

@Entity('signals')
@Index('idx_signals_instrument_status_ts', ['instrumentId', 'status', 'signalTimestamp'])
@Index('idx_signals_engine_status_ts', ['engine', 'status', 'signalTimestamp'])
export class Signals {
  /** UUID primary key — generated by TypeORM (uuid v4). */
  @PrimaryGeneratedColumn('uuid')
  id!: string;

  /** Strategy that generated this signal. */
  @ManyToOne(() => Strategies, { nullable: false, onDelete: 'CASCADE' })
  @JoinColumn({ name: 'strategy_id' })
  strategy!: Strategies;

  /**
   * Convenience read-only accessor for the strategy FK column value.
   * Populated by TypeORM from the strategy_id join column; not a separate DB column.
   */
  @RelationId((s: Signals) => s.strategy)
  strategyId!: string;

  /**
   * FK → instruments.id — the option contract this signal targets.
   * Stored as a plain UUID column; a @ManyToOne relation is available via
   * the Instruments entity (instruments.entity.ts).
   */
  @Column({ type: 'uuid', name: 'instrument_id' })
  instrumentId!: string;

  /** Trading engine context: 'LIVE' | 'PAPER'. */
  @Column({ type: 'varchar' })
  engine!: SignalEngine;

  /** Trade direction: 'BUY' | 'SELL'. */
  @Column({ type: 'varchar' })
  direction!: SignalDirection;

  /** Proposed entry price at signal-generation time (INR). */
  @Column({ type: 'numeric', precision: 12, scale: 2, name: 'entry_price' })
  entryPrice!: string;

  /** Stop-loss price as computed by the strategy (INR). */
  @Column({ type: 'numeric', precision: 12, scale: 2, name: 'stop_loss_price' })
  stopLossPrice!: string;

  /** Target price as computed by the strategy (INR). */
  @Column({ type: 'numeric', precision: 12, scale: 2, name: 'target_price' })
  targetPrice!: string;

  /** Proposed position size in lots. */
  @Column({ type: 'integer', name: 'position_size' })
  positionSize!: number;

  /** Weighted composite score (0.00 – 100.00). Must be ≥ 80 to proceed. */
  @Column({ type: 'numeric', precision: 5, scale: 2, name: 'composite_score' })
  compositeScore!: string;

  // ── 8 component scores ──────────────────────────────────────────────────────

  /** Score: regime alignment with the strategy's compatible_regimes list. */
  @Column({ type: 'numeric', precision: 4, scale: 2, name: 'score_regime_alignment' })
  scoreRegimeAlignment!: string;

  /** Score: price structure quality (support/resistance, trend alignment). */
  @Column({ type: 'numeric', precision: 4, scale: 2, name: 'score_price_structure' })
  scorePriceStructure!: string;

  /** Score: volume confirmation of the price move. */
  @Column({ type: 'numeric', precision: 4, scale: 2, name: 'score_volume_confirmation' })
  scoreVolumeConfirmation!: string;

  /** Score: momentum indicator alignment (RSI, MACD, etc.). */
  @Column({ type: 'numeric', precision: 4, scale: 2, name: 'score_momentum' })
  scoreMomentum!: string;

  /** Score: VWAP trend alignment. */
  @Column({ type: 'numeric', precision: 4, scale: 2, name: 'score_vwap_trend' })
  scoreVwapTrend!: string;

  /** Score: options/futures market confirmation (OI, PCR, futures basis). */
  @Column({ type: 'numeric', precision: 4, scale: 2, name: 'score_options_futures' })
  scoreOptionsFutures!: string;

  /** Score: liquidity and execution feasibility (bid-ask spread, volume depth). */
  @Column({ type: 'numeric', precision: 4, scale: 2, name: 'score_liquidity_execution' })
  scoreLiquidityExecution!: string;

  /** Score: Risk:Reward quality of the proposed trade. */
  @Column({ type: 'numeric', precision: 4, scale: 2, name: 'score_rr_quality' })
  scoreRrQuality!: string;

  // ─────────────────────────────────────────────────────────────────────────────

  /**
   * Raw input values that fed the 8 scoring components.
   * Stored as JSONB to support future schema evolution without migrations.
   */
  @Column({ type: 'jsonb', name: 'measured_inputs' })
  measuredInputs!: Record<string, unknown>;

  /**
   * Signal lifecycle status.
   *   'active'   — generated, awaiting ExecutionService evaluation
   *   'accepted' — within pre-trade checks, forwarded to ExecutionService
   *   'rejected' — failed a pre-trade check (see rejectionReason)
   *   'expired'  — TTL elapsed before acceptance
   *   'executed' — order placed for this signal
   */
  @Column({ type: 'varchar' })
  status!: SignalStatus;

  /** Human-readable reason if status = 'rejected'. NULL otherwise. */
  @Column({ type: 'varchar', name: 'rejection_reason', nullable: true })
  rejectionReason!: string | null;

  /** UTC timestamp when the signal was generated by SignalScoring. */
  @Column({ type: 'timestamptz', name: 'signal_timestamp' })
  signalTimestamp!: Date;

  /** UTC deadline after which the signal must not be executed. */
  @Column({ type: 'timestamptz', name: 'expiry_timestamp', nullable: true })
  expiryTimestamp!: Date | null;

  /** Dhan order ID, populated once an order is placed for this signal. */
  @Column({ type: 'varchar', name: 'dhan_order_id', nullable: true })
  dhanOrderId!: string | null;

  /** Market regime code active at signal-generation time (denormalised for fast reporting). */
  @Column({ type: 'varchar', nullable: true })
  regime!: string | null;

  /** Row creation timestamp (UTC). */
  @CreateDateColumn({ type: 'timestamptz', name: 'created_at' })
  createdAt!: Date;
}
