/**
 * Trades entity — immutable record of a completed round-trip trade
 * (entry → exit), including full cost breakdown and quality metrics.
 *
 * Implements append-only semantics per the Audit Trail design principle:
 * no record is modified or deleted after initial creation.
 *
 * Key analytics columns:
 *   - qcr: Quality-to-Cost Ratio — net_pnl / (total_costs + slippage)
 *   - exit_classification: qualitative assessment of exit timing vs. MFE
 *   - execution_quality: composite grade for fill quality
 *
 * Requirements: 16.6 (trade record completeness), 18.1 (schema)
 *
 * NUMERIC columns are typed as `string` because PostgreSQL NUMERIC can exceed
 * IEEE-754 double precision; TypeORM/pg returns them as strings by default.
 *
 * `!` definite-assignment assertions are used on all ORM-populated properties
 * because TypeORM hydrates instances at runtime, not via constructors.
 */

import {
  Entity,
  PrimaryGeneratedColumn,
  Column,
  CreateDateColumn,
  ManyToOne,
  JoinColumn,
  Index,
} from 'typeorm';
import { Position } from './positions.entity';

/** Exit timing classification relative to the trade's MFE. */
export type ExitClassification = 'premature' | 'near-optimal' | 'late' | 'no-favorable-excursion';

/** Composite execution quality grade. */
export type ExecutionQuality = 'Poor' | 'Fair' | 'Good' | 'Excellent' | 'No Favorable Excursion';

@Entity('trades')
@Index('idx_trades_engine_entry_time', ['engine', 'entry_time'])
@Index('idx_trades_strategy_engine_entry_time', ['strategy_id', 'engine', 'entry_time'])
export class Trade {
  /** UUID primary key — generated by TypeORM (uuid v4). */
  @PrimaryGeneratedColumn('uuid')
  id!: string;

  /** Execution engine that produced this trade — strictly isolated. */
  @Column({ type: 'varchar', length: 10 })
  engine!: string; // 'LIVE' | 'PAPER'

  /**
   * FK → positions.id — the position this trade closes (or partially closes).
   * Stored as both a plain column (for raw queries) and a typed relation.
   */
  @Column({ name: 'position_id', type: 'uuid' })
  position_id!: string;

  @ManyToOne(() => Position, (position) => position.trades, {
    nullable: false,
    onDelete: 'RESTRICT',
  })
  @JoinColumn({ name: 'position_id' })
  position!: Position;

  /** FK → instruments.id — the instrument traded. */
  @Column({ name: 'instrument_id', type: 'uuid' })
  instrument_id!: string;

  /** FK → strategies.id — the strategy that generated the entry signal. */
  @Column({ name: 'strategy_id', type: 'uuid' })
  strategy_id!: string;

  /**
   * FK → signals.id — the signal that initiated entry.
   * NULL for manually triggered trades or system-level square-offs.
   */
  @Column({ name: 'signal_id', type: 'uuid', nullable: true })
  signal_id!: string | null;

  /** Trade direction. */
  @Column({ type: 'varchar', length: 5 })
  direction!: string; // 'LONG' | 'SHORT'

  /** Total quantity (in units, not lots) for this trade record. */
  @Column({ type: 'integer' })
  quantity!: number;

  /**
   * Contract lot size at the time of the trade.
   * Captured at trade time because NSE lot sizes can change on expiry roll.
   */
  @Column({ name: 'lot_size', type: 'integer' })
  lot_size!: number;

  /** Volume-weighted average entry price (NUMERIC 12,2). */
  @Column({ name: 'entry_price', type: 'numeric', precision: 12, scale: 2 })
  entry_price!: string;

  /** Volume-weighted average exit price (NUMERIC 12,2). */
  @Column({ name: 'exit_price', type: 'numeric', precision: 12, scale: 2 })
  exit_price!: string;

  /** UTC timestamp of the first entry execution. */
  @Column({ name: 'entry_time', type: 'timestamptz' })
  entry_time!: Date;

  /** UTC timestamp of the final exit execution. */
  @Column({ name: 'exit_time', type: 'timestamptz' })
  exit_time!: Date;

  /**
   * Maximum Favorable Excursion for this trade (NUMERIC 15,2).
   * Copied from the parent Position at trade close time.
   */
  @Column({ type: 'numeric', precision: 15, scale: 2 })
  mfe!: string;

  /**
   * Maximum Adverse Excursion for this trade (NUMERIC 15,2).
   * Copied from the parent Position at trade close time.
   */
  @Column({ type: 'numeric', precision: 15, scale: 2 })
  mae!: string;

  // ── P&L components ─────────────────────────────────────────────────────────

  /**
   * Gross P&L before any costs: (exit_price − entry_price) × quantity
   * for LONG; (entry_price − exit_price) × quantity for SHORT (NUMERIC 15,2).
   */
  @Column({ name: 'gross_pnl', type: 'numeric', precision: 15, scale: 2 })
  gross_pnl!: string;

  /** Broker brokerage charge (NUMERIC 10,4). */
  @Column({ type: 'numeric', precision: 10, scale: 4 })
  brokerage!: string;

  /** Securities Transaction Tax (NUMERIC 10,4). */
  @Column({ type: 'numeric', precision: 10, scale: 4 })
  stt!: string;

  /** NSE/BSE exchange transaction charge (NUMERIC 10,4). */
  @Column({ name: 'exchange_charges', type: 'numeric', precision: 10, scale: 4 })
  exchange_charges!: string;

  /** Goods and Services Tax on brokerage + exchange charges (NUMERIC 10,4). */
  @Column({ type: 'numeric', precision: 10, scale: 4 })
  gst!: string;

  /** SEBI regulatory fee (NUMERIC 10,4). */
  @Column({ name: 'sebi_charges', type: 'numeric', precision: 10, scale: 4 })
  sebi_charges!: string;

  /** State-level stamp duty (NUMERIC 10,4). */
  @Column({ name: 'stamp_duty', type: 'numeric', precision: 10, scale: 4 })
  stamp_duty!: string;

  /**
   * Net P&L after all costs:
   *   gross_pnl − (brokerage + stt + exchange_charges + gst + sebi_charges + stamp_duty)
   * (NUMERIC 15,2).  Used by PortfolioModule to compute Dynamic_Capital.
   */
  @Column({ name: 'net_pnl', type: 'numeric', precision: 15, scale: 2 })
  net_pnl!: string;

  // ── Metadata & quality metrics ─────────────────────────────────────────────

  /** Human-readable reason for the exit (e.g. 'SL_HIT', 'TARGET_HIT', 'MANDATORY_EXIT'). */
  @Column({ name: 'exit_reason', type: 'varchar' })
  exit_reason!: string;

  /**
   * Observed total execution slippage for this trade: sum of entry and exit
   * fill slippages (NUMERIC 10,4).
   */
  @Column({ name: 'execution_slippage', type: 'numeric', precision: 10, scale: 4 })
  execution_slippage!: string;

  /**
   * Composite signal score at entry time (NUMERIC 5,2).
   * NULL for trades entered without a scored signal.
   */
  @Column({ name: 'signal_score', type: 'numeric', precision: 5, scale: 2, nullable: true })
  signal_score!: string | null;

  /** Dhan order ID for the entry order leg. */
  @Column({ name: 'dhan_entry_order_id', type: 'varchar', nullable: true })
  dhan_entry_order_id!: string | null;

  /** Dhan order ID for the exit order leg. */
  @Column({ name: 'dhan_exit_order_id', type: 'varchar', nullable: true })
  dhan_exit_order_id!: string | null;

  /**
   * Quality-to-Cost Ratio (NUMERIC 8,4).
   * Computed as: net_pnl / (total_transaction_costs + |execution_slippage|).
   * NULL when costs + slippage = 0 (to avoid division by zero).
   * A higher QCR indicates better execution relative to cost burden.
   */
  @Column({ type: 'numeric', precision: 8, scale: 4, nullable: true })
  qcr!: string | null;

  /**
   * Qualitative assessment of exit timing relative to this trade's MFE.
   *
   *   'premature'              — exited well before MFE was reached
   *   'near-optimal'           — exited close to MFE
   *   'late'                   — held past MFE, gave back significant gains
   *   'no-favorable-excursion' — MFE ≤ 0; trade never moved in our favour
   *
   * NULL until the classification algorithm runs post-close.
   */
  @Column({ name: 'exit_classification', type: 'varchar', nullable: true })
  exit_classification!: ExitClassification | null;

  /**
   * Composite execution quality grade combining fill price, slippage, and timing.
   *
   *   'Poor'                   — significant adverse slippage or delayed fills
   *   'Fair'                   — moderate slippage within acceptable range
   *   'Good'                   — fills close to expected with minimal slippage
   *   'Excellent'              — fills at or better than expected price
   *   'No Favorable Excursion' — trade had no positive price movement to evaluate
   *
   * NULL until the quality scoring algorithm runs post-close.
   */
  @Column({ name: 'execution_quality', type: 'varchar', nullable: true })
  execution_quality!: ExecutionQuality | null;

  /** UTC timestamp when the row was first inserted. */
  @CreateDateColumn({ name: 'created_at', type: 'timestamptz' })
  created_at!: Date;
}
