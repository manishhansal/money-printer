/**
 * Executions entity — records each individual fill event for an order.
 *
 * An order can produce multiple execution rows when it is filled partially
 * (i.e. a PARTIAL fill followed by one or more further fills).
 *
 * Requirements: 18.1 (schema)
 *
 * NUMERIC columns are typed as `string` because PostgreSQL NUMERIC can exceed
 * IEEE-754 double precision; TypeORM/pg returns them as strings by default.
 *
 * `!` definite-assignment assertions are used on all ORM-populated properties
 * because TypeORM hydrates instances at runtime, not via constructors.
 */

import {
  Entity,
  PrimaryGeneratedColumn,
  Column,
  CreateDateColumn,
  ManyToOne,
  JoinColumn,
  Index,
} from 'typeorm';
import { Order } from './orders.entity';

@Entity('executions')
@Index('idx_executions_order_id', ['order_id'])
export class Execution {
  /** UUID primary key — generated by TypeORM (uuid v4). */
  @PrimaryGeneratedColumn('uuid')
  id!: string;

  /**
   * FK → orders.id — the parent order this fill belongs to.
   * Stored as both a plain column (for raw queries) and a typed relation.
   */
  @Column({ name: 'order_id', type: 'uuid' })
  order_id!: string;

  @ManyToOne(() => Order, (order) => order.executions, {
    nullable: false,
    onDelete: 'RESTRICT',
  })
  @JoinColumn({ name: 'order_id' })
  order!: Order;

  /** Execution engine that produced this fill — must match the parent order. */
  @Column({ type: 'varchar', length: 10 })
  engine!: string; // 'LIVE' | 'PAPER'

  /**
   * Dhan platform trade ID for this specific fill.
   * NULL for simulated PaperEngine fills that have no broker representation.
   */
  @Column({ name: 'dhan_trade_id', type: 'varchar', nullable: true })
  dhan_trade_id!: string | null;

  /**
   * Actual fill price for this execution (NUMERIC 12,2).
   * For PaperEngine: best bid (SELL) or best ask (BUY) at fill time.
   */
  @Column({ name: 'fill_price', type: 'numeric', precision: 12, scale: 2 })
  fill_price!: string;

  /** Number of units/lots filled in this execution. */
  @Column({ name: 'fill_quantity', type: 'integer' })
  fill_quantity!: number;

  /** UTC timestamp when the broker confirmed this fill. */
  @Column({ name: 'fill_timestamp', type: 'timestamptz' })
  fill_timestamp!: Date;

  /**
   * Observed slippage for this fill: |fill_price − expected_price| (NUMERIC 10,4).
   * NULL when slippage measurement is not available (e.g. MARKET orders with
   * no reference price at submission time).
   */
  @Column({ type: 'numeric', precision: 10, scale: 4, nullable: true })
  slippage!: string | null;

  /** UTC timestamp when the row was first inserted. */
  @CreateDateColumn({ name: 'created_at', type: 'timestamptz' })
  created_at!: Date;
}
