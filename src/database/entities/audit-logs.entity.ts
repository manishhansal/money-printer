/**
 * AuditLogs entity — immutable audit trail for every security-relevant and
 * user-initiated action in the CloudEngine.
 *
 * Written by: AuthModule (login/logout/token events), TradeJournal
 * (configuration_changes record set), LiveEngine (arm/disarm, kill switch),
 * and ReconciliationService (discrepancy acknowledgments).
 *
 * `previousValue` and `newValue` are encrypted at rest because they may
 * contain sensitive configuration data (e.g. API key prefixes, risk limits).
 *
 * Append-only semantics: no UPDATE or DELETE is ever issued on this table.
 *
 * Requirements: 13.4, 16.8, 16.9, 18.1
 */

import { Column, CreateDateColumn, Entity, Index, PrimaryGeneratedColumn } from 'typeorm';
import { encryptedColumnTransformer } from '../../common/transformers/encrypted-column.transformer';

/** All discrete audit event categories. */
export enum AuditEventType {
  // Auth events
  LOGIN = 'LOGIN',
  LOGIN_FAILURE = 'LOGIN_FAILURE',
  TOKEN_REFRESH = 'TOKEN_REFRESH',
  TOKEN_EXPIRY = 'TOKEN_EXPIRY',
  LOGOUT = 'LOGOUT',
  // Configuration / operational events
  CONFIG_CHANGE = 'CONFIG_CHANGE',
  TRADE_AUTH = 'TRADE_AUTH',
  KILL_SWITCH = 'KILL_SWITCH',
  ARM_DISARM = 'ARM_DISARM',
  RECONCILIATION_ACTION = 'RECONCILIATION_ACTION',
}

/** Outcome of the audited action. */
export enum AuditOutcome {
  SUCCESS = 'SUCCESS',
  FAILURE = 'FAILURE',
}

@Entity('audit_logs')
@Index('idx_audit_logs_user_timestamp', ['userId', 'timestamp'])
@Index('idx_audit_logs_event_type_timestamp', ['eventType', 'timestamp'])
export class AuditLogs {
  /** UUID primary key — generated by TypeORM (uuid v4). */
  @PrimaryGeneratedColumn('uuid')
  id!: string;

  /**
   * Authenticated user who initiated the action.
   * NULL for system-initiated actions (e.g. automated reconciliation).
   */
  @Column({ name: 'user_id', type: 'varchar', nullable: true })
  userId!: string | null;

  /** Category of the audited event. */
  @Column({ name: 'event_type', type: 'varchar' })
  eventType!: string;

  /**
   * Entity type affected by the change (e.g. "UserSettings", "Strategy").
   * NULL for non-entity-scoped events (e.g. login, kill switch).
   */
  @Column({ name: 'entity_type', type: 'varchar', nullable: true })
  entityType!: string | null;

  /**
   * UUID of the specific entity row that was modified.
   * NULL when `entityType` is NULL.
   */
  @Column({ name: 'entity_id', type: 'uuid', nullable: true })
  entityId!: string | null;

  /**
   * Name of the configuration field that was changed.
   * NULL for non-field-scoped events.
   */
  @Column({ name: 'field_name', type: 'varchar', nullable: true })
  fieldName!: string | null;

  /**
   * Value of the field before the change — encrypted at rest.
   * NULL when the field was newly created or is not applicable.
   */
  @Column({
    name: 'previous_value',
    type: 'varchar',
    nullable: true,
    transformer: encryptedColumnTransformer,
  })
  previousValue!: string | null;

  /**
   * Value of the field after the change — encrypted at rest.
   * NULL when the field was deleted or is not applicable.
   */
  @Column({
    name: 'new_value',
    type: 'varchar',
    nullable: true,
    transformer: encryptedColumnTransformer,
  })
  newValue!: string | null;

  /**
   * IP address of the client that initiated the action.
   * Stored as TEXT (PostgreSQL INET not directly supported by TypeORM).
   * NULL for internally-triggered system actions.
   */
  @Column({ name: 'ip_address', type: 'varchar', nullable: true })
  ipAddress!: string | null;

  /**
   * Arbitrary structured metadata for the event (stack traces, session IDs, etc.).
   * NULL when no additional context is available.
   */
  @Column({ type: 'jsonb', nullable: true })
  metadata!: Record<string, unknown> | null;

  /** Whether the action succeeded or failed. */
  @Column({ type: 'varchar', length: 10 })
  outcome!: string;

  /** UTC timestamp when the event occurred. */
  @Column({ type: 'timestamptz' })
  timestamp!: Date;

  /** Row insertion timestamp (UTC) — set once by the database on INSERT. */
  @CreateDateColumn({ name: 'created_at', type: 'timestamptz' })
  createdAt!: Date;
}
