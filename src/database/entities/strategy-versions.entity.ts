/**
 * StrategyVersions entity — immutable audit trail of every configuration
 * snapshot taken whenever a Strategy's parameters change.
 *
 * Each (strategy_id, version) pair is unique; version numbers are managed by
 * the application layer and mirror `Strategies.version` at the time of capture.
 *
 * `!` definite-assignment assertions are used on all ORM-populated properties
 * because TypeORM hydrates instances at runtime, not via constructors.
 *
 * Requirements: 18.1
 */

import {
  Column,
  CreateDateColumn,
  Entity,
  JoinColumn,
  ManyToOne,
  PrimaryGeneratedColumn,
  RelationId,
  Unique,
} from 'typeorm';
import { Strategies } from './strategies.entity';

@Entity('strategy_versions')
@Unique('uq_strategy_versions_strategy_version', ['strategy', 'version'])
export class StrategyVersions {
  /** UUID primary key — generated by TypeORM (uuid v4). */
  @PrimaryGeneratedColumn('uuid')
  id!: string;

  /** Parent strategy — cascade-delete removes all version history on strategy removal. */
  @ManyToOne(() => Strategies, { nullable: false, onDelete: 'CASCADE' })
  @JoinColumn({ name: 'strategy_id' })
  strategy!: Strategies;

  /**
   * Convenience read-only accessor for the strategy FK column value.
   * Populated by TypeORM from the strategy_id join column; not a separate DB column.
   */
  @RelationId((sv: StrategyVersions) => sv.strategy)
  strategyId!: string;

  /** Version number of this snapshot (matches Strategies.version at capture time). */
  @Column({ type: 'integer' })
  version!: number;

  /**
   * Full JSON snapshot of the strategy configuration at the time this version
   * was created — entry/exit/invalidation conditions, limits, thresholds, etc.
   */
  @Column({ type: 'jsonb', name: 'config_snapshot' })
  configSnapshot!: Record<string, unknown>;

  /** Row creation timestamp (UTC). */
  @CreateDateColumn({ type: 'timestamptz', name: 'created_at' })
  createdAt!: Date;
}
