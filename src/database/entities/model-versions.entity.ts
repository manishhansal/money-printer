/**
 * ModelVersions entity — versioned registry of ML model checkpoints.
 *
 * Each row represents a distinct training checkpoint of a named ML model
 * (e.g. SignalScorer weights, RegimeClassifier).  The lifecycle progresses
 * through: UNTRAINED → SHADOW → VALIDATED → PRODUCTION.
 *
 * Only one version per model_name may hold PRODUCTION state at a time;
 * this invariant is enforced at the application layer by the BacktestEngine
 * before updating a row's state.
 *
 * Requirements: 18.1, 18.2
 */

import {
  Entity,
  PrimaryGeneratedColumn,
  Column,
  CreateDateColumn,
  UpdateDateColumn,
} from 'typeorm';

/** Lifecycle states of a trained ML model version. */
export type ModelVersionState = 'UNTRAINED' | 'SHADOW' | 'VALIDATED' | 'PRODUCTION';

@Entity('model_versions')
export class ModelVersions {
  /** Surrogate UUID primary key — generated by TypeORM via the `uuid` package. */
  @PrimaryGeneratedColumn('uuid')
  id!: string;

  /**
   * Logical name of the model family (e.g. "SignalScorer", "RegimeClassifier").
   * Combined with `version` to uniquely identify a checkpoint.
   */
  @Column({ type: 'varchar', length: 100 })
  model_name!: string;

  /**
   * Monotonically increasing version integer within the model_name namespace.
   * Version 1 is the first trained checkpoint; subsequent retrains increment by 1.
   */
  @Column({ type: 'int' })
  version!: number;

  /** Current lifecycle state of this model version. */
  @Column({ type: 'varchar', length: 20 })
  state!: ModelVersionState;

  /**
   * Opaque reference to the training dataset used (e.g. S3 URI, GCS path,
   * or a date-range descriptor such as "2023-01-01/2024-06-30").
   * NULL when the model has not yet been trained.
   */
  @Column({ type: 'varchar', length: 500, nullable: true })
  training_dataset_ref!: string | null;

  /**
   * JSONB snapshot of the feature definitions at training time.
   * Captures feature names, types, transformations, and any derived indicators
   * so that the exact feature set can be reproduced for inference.
   * NULL when the model has not yet been trained.
   */
  @Column({ type: 'jsonb', nullable: true })
  feature_definitions!: Record<string, unknown> | null;

  /** Row creation timestamp (UTC); set once by the database on INSERT. */
  @CreateDateColumn({ type: 'timestamptz' })
  created_at!: Date;

  /** Last update timestamp (UTC); automatically refreshed on every UPDATE. */
  @UpdateDateColumn({ type: 'timestamptz' })
  updated_at!: Date;
}
