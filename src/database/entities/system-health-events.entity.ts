/**
 * SystemHealthEvents entity — append-only log of every module health event,
 * infrastructure failure, and automated restart attempt.
 *
 * Rows are written by any module that experiences a startup failure, unhandled
 * exception, or state transition from Healthy → Degraded → Down.  The entity
 * is shared across the TradeJournal (system_errors record set), the
 * SystemHealthMonitor, and the CapitalLedger failure handler.
 *
 * Append-only semantics: no UPDATE or DELETE is ever issued on this table.
 *
 * Requirements: 2.7, 2.8, 13.1, 18.1
 */

import { Column, CreateDateColumn, Entity, Index, PrimaryGeneratedColumn } from 'typeorm';

/** Severity classification for health events. */
export type HealthEventSeverity = 'INFO' | 'WARNING' | 'CRITICAL';

@Entity('system_health_events')
@Index('idx_system_health_events_module_timestamp', ['module_name', 'timestamp'])
@Index('idx_system_health_events_severity_timestamp', ['severity', 'timestamp'])
export class SystemHealthEvents {
  /** UUID primary key — generated by TypeORM (uuid v4). */
  @PrimaryGeneratedColumn('uuid')
  id!: string;

  /**
   * Category of health event.
   * Examples: "MODULE_RESTART", "DB_CONNECTION_FAILURE", "UNHANDLED_EXCEPTION",
   *           "CAPITAL_LEDGER_FAILURE", "BACKUP_COMPLETE", "BACKUP_FAILURE"
   */
  @Column({ name: 'event_type', type: 'varchar' })
  event_type!: string;

  /**
   * Name of the CloudEngine module that emitted the event.
   * Examples: "TradeJournal", "RiskManagement", "ExecutionService"
   */
  @Column({ name: 'module_name', type: 'varchar' })
  module_name!: string;

  /** Severity level classifying operational impact. */
  @Column({ type: 'varchar', length: 10 })
  severity!: HealthEventSeverity;

  /** Human-readable description of the event. */
  @Column({ type: 'text' })
  message!: string;

  /**
   * Arbitrary structured context attached to the event.
   * JSONB allows schema-free storage of stack traces, error codes, and
   * module-specific diagnostic data.
   * NULL when no additional metadata is available.
   */
  @Column({ type: 'jsonb', nullable: true })
  metadata!: Record<string, unknown> | null;

  /** UTC timestamp when the event occurred in the CloudEngine. */
  @Column({ type: 'timestamptz' })
  timestamp!: Date;

  /** Row insertion timestamp (UTC) — set once by the database on INSERT. */
  @CreateDateColumn({ name: 'created_at', type: 'timestamptz' })
  created_at!: Date;
}
