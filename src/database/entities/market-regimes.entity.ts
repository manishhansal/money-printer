/**
 * MarketRegimes entity — persists every market-regime classification produced
 * by the MarketRegime module (at most once per 60 seconds during trading hours).
 *
 * Regime codes (exactly one of 10 values):
 *   TRENDING_BULLISH | TRENDING_BEARISH | RANGING | HIGH_VOLATILITY |
 *   LOW_VOLATILITY   | BREAKOUT         | REVERSAL | GAP_UP | GAP_DOWN | UNSTABLE
 *
 * `!` definite-assignment assertions are used on all ORM-populated properties
 * because TypeORM hydrates instances at runtime, not via constructors.
 *
 * Requirements: 18.1
 */

import { Column, Entity, Index, PrimaryGeneratedColumn } from 'typeorm';

@Entity('market_regimes')
@Index('idx_market_regimes_classified_at', ['classifiedAt'])
export class MarketRegimes {
  /** UUID primary key — generated by TypeORM (uuid v4). */
  @PrimaryGeneratedColumn('uuid')
  id!: string;

  /** One of the 10 defined regime codes. */
  @Column({ type: 'varchar', name: 'regime' })
  regime!: string;

  /** UTC timestamp of when the classification was produced. */
  @Column({ type: 'timestamptz', name: 'classified_at' })
  classifiedAt!: Date;

  /** NIFTY price trend label (e.g. "BULLISH", "BEARISH", "SIDEWAYS"). */
  @Column({ type: 'varchar', name: 'nifty_trend' })
  niftyTrend!: string;

  /** BANKNIFTY price trend label. */
  @Column({ type: 'varchar', name: 'banknifty_trend' })
  bankniftyTrend!: string;

  /**
   * Market breadth reading (0.00 – 100.00).
   * NUMERIC(5,2) — returned as string by pg to preserve precision.
   */
  @Column({ type: 'numeric', precision: 5, scale: 2, name: 'market_breadth' })
  marketBreadth!: string;

  /** Advance/Decline ratio at classification time. */
  @Column({ type: 'numeric', precision: 8, scale: 4, name: 'advance_decline_ratio' })
  advanceDeclineRatio!: string;

  /** VWAP deviation of NIFTY at classification time. */
  @Column({ type: 'numeric', precision: 8, scale: 4, name: 'vwap_deviation' })
  vwapDeviation!: string;

  /** India VIX value at classification time. */
  @Column({ type: 'numeric', precision: 6, scale: 2, name: 'india_vix' })
  indiaVix!: string;

  /** Average True Range used in classification. */
  @Column({ type: 'numeric', precision: 10, scale: 4, name: 'atr' })
  atr!: string;

  /** Relative volume ratio at classification time. */
  @Column({ type: 'numeric', precision: 8, scale: 4, name: 'relative_volume' })
  relativeVolume!: string;

  /**
   * Sector strength indicator.
   * Nullable — may not be available during pre-market or data-feed gaps.
   */
  @Column({ type: 'numeric', precision: 5, scale: 2, name: 'sector_strength', nullable: true })
  sectorStrength!: string | null;

  /**
   * Nifty futures basis.
   * Nullable — not applicable for regimes derived solely from cash-market data.
   */
  @Column({ type: 'numeric', precision: 8, scale: 4, name: 'futures_basis', nullable: true })
  futuresBasis!: string | null;

  /** Human-readable rationale explaining the classification decision. */
  @Column({ type: 'text', name: 'classification_rationale', nullable: true })
  classificationRationale!: string | null;
}
