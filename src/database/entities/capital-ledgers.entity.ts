/**
 * CapitalLedgers entity — append-only ledger tracking every change to Dynamic Capital.
 *
 * Each row records a discrete financial event (trade P&L, manual deposit/withdrawal,
 * or compounding transfer) together with the balance snapshot immediately before and
 * after the event.  Rows are never updated or deleted; all corrections are new entries.
 *
 * FK note: trade_id references the Trades table (implemented in task 3.1).
 * The @ManyToOne relation will be wired once that entity exists; until then the
 * column is a bare UUID so migrations can create the FK constraint independently.
 *
 * Requirements: 18.1, 18.2
 *
 * NUMERIC columns are typed as `string` because PostgreSQL NUMERIC can exceed
 * IEEE-754 double precision; TypeORM/pg returns them as strings by default.
 */

import { Entity, PrimaryGeneratedColumn, Column, CreateDateColumn, Index } from 'typeorm';

/** Trading engine context — completely isolated namespaces. */
export type EngineType = 'LIVE' | 'PAPER';

/** Categories of ledger event that can affect Dynamic Capital. */
export type CapitalLedgerEventType =
  'TRADE_PNL' | 'MANUAL_DEPOSIT' | 'MANUAL_WITHDRAWAL' | 'COMPOUNDING';

@Entity('capital_ledgers')
@Index('idx_capital_ledgers_engine_occurred_at', ['engine', 'occurred_at'])
export class CapitalLedgers {
  /** Surrogate UUID primary key — generated by TypeORM via the `uuid` package. */
  @PrimaryGeneratedColumn('uuid')
  id!: string;

  /** Trading engine this ledger entry belongs to. */
  @Column({ type: 'varchar', length: 10 })
  engine!: EngineType;

  /** Type of financial event that caused the capital change. */
  @Column({ type: 'varchar', length: 30 })
  event_type!: CapitalLedgerEventType;

  /**
   * Optional reference to the trade that generated this P&L entry.
   * NULL for non-trade events (deposits, withdrawals, compounding).
   * FK → Trades(id) — constraint added in migration once Trades table exists.
   */
  @Column({ type: 'uuid', nullable: true })
  trade_id!: string | null;

  /**
   * Signed monetary amount of the event (positive = credit, negative = debit).
   * Stored as NUMERIC(15,2); TypeORM returns PostgreSQL NUMERIC as a string to
   * preserve full decimal precision without floating-point rounding.
   */
  @Column({ type: 'decimal', precision: 15, scale: 2 })
  amount!: string;

  /** Capital balance immediately before this event was applied. */
  @Column({ type: 'decimal', precision: 15, scale: 2 })
  balance_before!: string;

  /** Capital balance immediately after this event was applied. */
  @Column({ type: 'decimal', precision: 15, scale: 2 })
  balance_after!: string;

  /** Optional human-readable note (e.g. reason for manual adjustment). */
  @Column({ type: 'varchar', length: 500, nullable: true })
  description!: string | null;

  /** UTC timestamp when the financial event occurred. */
  @Column({ type: 'timestamptz' })
  occurred_at!: Date;

  /** Row creation timestamp (UTC); set once by the database on INSERT. */
  @CreateDateColumn({ type: 'timestamptz' })
  created_at!: Date;
}
