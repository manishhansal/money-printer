/**
 * DailyTradingSummaries entity — one-row-per-day-per-engine aggregate snapshot.
 *
 * Summarises the complete trading activity and capital outcome for a single
 * calendar day within a given engine (LIVE or PAPER).  The row is upserted
 * throughout the trading day as new trades close, then finalised at end-of-day
 * reconciliation.
 *
 * The UNIQUE constraint on (trading_date, engine) ensures exactly one summary
 * row exists per engine per day, enabling safe upsert semantics.
 *
 * Requirements: 18.1, 18.2
 *
 * NUMERIC columns are typed as `string` because PostgreSQL NUMERIC can exceed
 * IEEE-754 double precision; TypeORM/pg returns them as strings by default.
 */

import {
  Entity,
  PrimaryGeneratedColumn,
  Column,
  CreateDateColumn,
  UpdateDateColumn,
  Unique,
} from 'typeorm';

import { EngineType } from './capital-ledgers.entity';

@Entity('daily_trading_summaries')
@Unique('uq_daily_trading_summaries_date_engine', ['trading_date', 'engine'])
export class DailyTradingSummaries {
  /** Surrogate UUID primary key — generated by TypeORM via the `uuid` package. */
  @PrimaryGeneratedColumn('uuid')
  id!: string;

  /**
   * NSE calendar date this summary covers (date only, no time component).
   * Stored as PostgreSQL DATE; TypeORM returns it as a JS string 'YYYY-MM-DD'.
   */
  @Column({ type: 'date' })
  trading_date!: string;

  /** Trading engine this daily summary belongs to. */
  @Column({ type: 'varchar', length: 10 })
  engine!: EngineType;

  /** Total number of trades executed (both winning and losing). */
  @Column({ type: 'int', default: 0 })
  total_trades!: number;

  /** Number of trades that closed with a positive net P&L. */
  @Column({ type: 'int', default: 0 })
  winning_trades!: number;

  /** Number of trades that closed with a negative net P&L. */
  @Column({ type: 'int', default: 0 })
  losing_trades!: number;

  /**
   * Sum of gross P&L across all trades before deducting brokerage and charges.
   * Stored as NUMERIC(15,2); TypeORM returns PostgreSQL NUMERIC as a string.
   */
  @Column({ type: 'decimal', precision: 15, scale: 2, default: '0.00' })
  gross_pnl!: string;

  /** Total brokerage, STT, GST, and other exchange charges for the day. */
  @Column({ type: 'decimal', precision: 15, scale: 2, default: '0.00' })
  total_charges!: string;

  /** Net P&L after all charges; the authoritative daily performance figure. */
  @Column({ type: 'decimal', precision: 15, scale: 2, default: '0.00' })
  net_pnl!: string;

  /**
   * Dynamic Capital balance at market close (15:15 IST square-off complete).
   * NULL only if the day had no activity and no closing snapshot was taken.
   */
  @Column({ type: 'decimal', precision: 15, scale: 2, nullable: true })
  closing_capital!: string | null;

  /**
   * TRUE if the two-consecutive-loss lockout was activated during this session.
   * Immutable once set to TRUE (cleared only at the start of the next session).
   */
  @Column({ type: 'boolean', default: false })
  two_loss_lockout_triggered!: boolean;

  /** TRUE if an emergency halt was activated at any point during this session. */
  @Column({ type: 'boolean', default: false })
  emergency_halt_triggered!: boolean;

  /** TRUE if the user-initiated kill switch was engaged during this session. */
  @Column({ type: 'boolean', default: false })
  kill_switch_activated!: boolean;

  /**
   * Explanation for why no trades were taken on days with zero activity
   * (e.g. "EMERGENCY_HALT", "NO_VALID_SIGNALS", "SESSION_CLOSED").
   * NULL on active trading days.
   */
  @Column({ type: 'text', nullable: true })
  no_trade_reason!: string | null;

  /** Row creation timestamp (UTC); set once by the database on INSERT. */
  @CreateDateColumn({ type: 'timestamptz' })
  created_at!: Date;

  /** Last update timestamp (UTC); automatically refreshed on every UPDATE. */
  @UpdateDateColumn({ type: 'timestamptz' })
  updated_at!: Date;
}
