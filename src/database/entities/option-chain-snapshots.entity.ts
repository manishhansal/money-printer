/**
 * OptionChainSnapshots entity — stores full point-in-time option chain captures
 * for a given underlying and expiry, enriched with computed summary statistics.
 *
 * The raw chain (all strikes with Greeks, OI, IV, bid/ask) is stored as JSONB
 * in `chain_data` for flexible schema-free querying.  Derived summary columns
 * (PCR, IV ATM, total OI) are stored as first-class columns for fast
 * filtering without JSONB traversal.
 *
 * The compound index on (underlying, expiry_date, snapshot_at DESC) supports
 * efficient "latest chain snapshot for a given underlying + expiry" lookups
 * used by OptionsIntelligence and Strategy H.
 *
 * All financial values use NUMERIC to avoid floating-point precision loss.
 * Timestamps are stored in UTC (timestamp with time zone).
 *
 * The `!` definite assignment assertions tell TypeScript that TypeORM will
 * populate these properties at runtime (via hydration), not the constructor.
 *
 * Requirements: 18.1, 18.8
 */

import { Column, CreateDateColumn, Entity, Index, PrimaryGeneratedColumn } from 'typeorm';

/**
 * Compound index for fast "latest snapshot for underlying + expiry" queries.
 * NOTE: The migration for this index MUST specify `snapshot_at DESC` to avoid
 * a sort step on the most common query pattern.
 *
 * SQL equivalent:
 *   CREATE INDEX "IDX_option_chain_snapshots_underlying_expiry_snapshot_at"
 *     ON option_chain_snapshots (underlying, expiry_date, snapshot_at DESC);
 */
@Entity({ name: 'option_chain_snapshots' })
@Index('IDX_option_chain_snapshots_underlying_expiry_snapshot_at', [
  'underlying',
  'expiryDate',
  'snapshotAt',
])
export class OptionChainSnapshots {
  /** UUID primary key — generated by TypeORM (uuid package). */
  @PrimaryGeneratedColumn('uuid')
  id!: string;

  /**
   * Underlying index or stock symbol (e.g. "NIFTY", "BANKNIFTY").
   * Matches the `underlying` column in the instruments table.
   */
  @Column({ name: 'underlying', type: 'varchar' })
  underlying!: string;

  /**
   * Options expiry date for which this chain was captured.
   * Stored as a calendar date (no time component).
   * Part of the compound index for latest-snapshot lookups.
   */
  @Column({ name: 'expiry_date', type: 'date' })
  expiryDate!: string;

  /**
   * UTC timestamp at which this option chain snapshot was captured.
   * Indexed in DESC order with (underlying, expiry_date) — see class decorator.
   *
   * Requirement 7.1: Greeks data must not be older than 60 seconds when used
   * for contract selection — callers should compare `snapshotAt` against the
   * current time before using `chainData`.
   */
  @Column({ name: 'snapshot_at', type: 'timestamp with time zone' })
  snapshotAt!: Date;

  /**
   * Full option chain payload including all strikes, Greeks (Delta, Gamma,
   * Theta, Vega), IV, OI, bid/ask, and depth for both CE and PE legs.
   *
   * Schema is intentionally left flexible as JSONB to accommodate Dhan API
   * response structure changes without requiring schema migrations.
   */
  @Column({ name: 'chain_data', type: 'jsonb' })
  chainData!: Record<string, unknown>;

  /**
   * Aggregate call-side open interest across all strikes at snapshot time.
   * Nullable — may not be computable if chain data is incomplete.
   * BIGINT returned as string.
   */
  @Column({ name: 'total_call_oi', type: 'bigint', nullable: true })
  totalCallOi!: string | null;

  /**
   * Aggregate put-side open interest across all strikes at snapshot time.
   * Nullable — may not be computable if chain data is incomplete.
   * BIGINT returned as string.
   */
  @Column({ name: 'total_put_oi', type: 'bigint', nullable: true })
  totalPutOi!: string | null;

  /**
   * Put-Call Ratio computed as total_put_oi / total_call_oi at snapshot time.
   * NUMERIC(8,4) — supports values up to 9999.9999.
   * Nullable — undefined when either total OI is zero or unavailable.
   *
   * Used by OptionsIntelligence and Strategy H (Options Flow Intelligence).
   */
  @Column({
    name: 'pcr',
    type: 'numeric',
    precision: 8,
    scale: 4,
    nullable: true,
  })
  pcr!: string | null;

  /**
   * At-the-money implied volatility at snapshot time.
   * Computed as the IV of the ATM strike (closest to current underlying price).
   * NUMERIC(8,4) — stored as a decimal (e.g. 0.1825 represents 18.25% IV).
   * Nullable — undefined when ATM strike cannot be determined.
   *
   * Used by OptionsIntelligence to classify the IV regime (expanding /
   * contracting / neutral) per Requirement 7.3.
   */
  @Column({
    name: 'iv_atm',
    type: 'numeric',
    precision: 8,
    scale: 4,
    nullable: true,
  })
  ivAtm!: string | null;

  /**
   * UTC timestamp of row creation — set once by TypeORM on INSERT.
   * Distinct from `snapshotAt`, which records when the market data was
   * captured; `createdAt` records when the row was persisted.
   */
  @CreateDateColumn({
    name: 'created_at',
    type: 'timestamp with time zone',
  })
  createdAt!: Date;
}
