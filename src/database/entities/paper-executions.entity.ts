/**
 * PaperExecutions entity — isolated paper-trading mirror of the Executions table.
 *
 * Stored in `paper_executions` to guarantee zero overlap with the live
 * `executions` table (Requirement 10.1: no shared database tables between
 * PaperEngine and LiveEngine).
 *
 * Each row records a simulated fill for a PaperOrder. The `dhan_trade_id` is
 * always NULL because simulated fills never reach the Dhan broker.
 *
 * Requirements: 10.1
 */

import {
  Entity,
  PrimaryGeneratedColumn,
  Column,
  CreateDateColumn,
  ManyToOne,
  JoinColumn,
  Index,
} from 'typeorm';
import { PaperOrder } from './paper-orders.entity';

@Entity('paper_executions')
@Index('idx_paper_executions_order_id', ['order_id'])
export class PaperExecution {
  /** UUID primary key — generated by TypeORM (uuid v4). */
  @PrimaryGeneratedColumn('uuid')
  id!: string;

  /**
   * FK → paper_orders.id — the parent paper order this fill belongs to.
   * Stored as both a plain column (for raw queries) and a typed relation.
   */
  @Column({ name: 'order_id', type: 'uuid' })
  order_id!: string;

  @ManyToOne(() => PaperOrder, (order) => order.executions, {
    nullable: false,
    onDelete: 'RESTRICT',
  })
  @JoinColumn({ name: 'order_id' })
  order!: PaperOrder;

  /**
   * Engine identifier — always 'PAPER' for this table.
   * Retained to mirror the Executions schema.
   */
  @Column({ type: 'varchar', length: 10, default: 'PAPER' })
  engine!: string;

  /**
   * Dhan platform trade ID — always NULL for paper executions (no broker fill).
   * Column retained to mirror the Executions schema.
   */
  @Column({ name: 'dhan_trade_id', type: 'varchar', nullable: true })
  dhan_trade_id!: string | null;

  /**
   * Simulated fill price for this paper execution (NUMERIC 12,2).
   * For BUY orders: best ask ± slippage.
   * For SELL orders: best bid ± slippage.
   * (Requirements 10.2, 10.3, 10.5)
   */
  @Column({ name: 'fill_price', type: 'numeric', precision: 12, scale: 2 })
  fill_price!: string;

  /** Number of units/lots filled in this paper execution. */
  @Column({ name: 'fill_quantity', type: 'integer' })
  fill_quantity!: number;

  /** UTC timestamp when the simulated fill was processed. */
  @Column({ name: 'fill_timestamp', type: 'timestamptz' })
  fill_timestamp!: Date;

  /**
   * Simulated slippage for this fill: |fill_price − reference_price| (NUMERIC 10,4).
   * Reflects the configured slippage model's contribution to this fill.
   */
  @Column({ type: 'numeric', precision: 10, scale: 4, nullable: true })
  slippage!: string | null;

  /** UTC timestamp when the row was first inserted. */
  @CreateDateColumn({ name: 'created_at', type: 'timestamptz' })
  created_at!: Date;
}
