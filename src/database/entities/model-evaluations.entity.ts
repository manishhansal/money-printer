/**
 * ModelEvaluations entity — validation gate results for ML model versions.
 *
 * Each row records the outcome of a single validation run against a ModelVersion.
 * Multiple evaluation types (OOS, walk-forward, Monte Carlo) may be performed
 * per version; all must pass their respective gates before the version can be
 * promoted to VALIDATED or PRODUCTION state.
 *
 * This table is append-only: evaluations are never modified after creation.
 *
 * Requirements: 18.1, 18.2
 *
 * NUMERIC columns are typed as `string` because PostgreSQL NUMERIC can exceed
 * IEEE-754 double precision; TypeORM/pg returns them as strings by default.
 */

import {
  Entity,
  PrimaryGeneratedColumn,
  Column,
  CreateDateColumn,
  ManyToOne,
  JoinColumn,
  Index,
} from 'typeorm';

import { ModelVersions } from './model-versions.entity';

/** Types of statistical validation methodology. */
export type ValidationType = 'OOS' | 'WALK_FORWARD' | 'MONTE_CARLO';

@Entity('model_evaluations')
@Index('idx_model_evaluations_model_version_id', ['model_version_id'])
export class ModelEvaluations {
  /** Surrogate UUID primary key — generated by TypeORM via the `uuid` package. */
  @PrimaryGeneratedColumn('uuid')
  id!: string;

  /**
   * The model version this evaluation was performed against.
   * FK → ModelVersions(id); nullable: false — every evaluation must reference
   * a known model version.
   */
  @ManyToOne(() => ModelVersions, { nullable: false, onDelete: 'RESTRICT' })
  @JoinColumn({ name: 'model_version_id' })
  model_version!: ModelVersions;

  /** UUID FK column exposed for direct querying without a JOIN. */
  @Column({ type: 'uuid' })
  model_version_id!: string;

  /** UTC timestamp when this evaluation run completed. */
  @Column({ type: 'timestamptz' })
  evaluated_at!: Date;

  /** Statistical methodology used for this validation run. */
  @Column({ type: 'varchar', length: 20 })
  validation_type!: ValidationType;

  /**
   * Mathematical expectancy: average profit per unit of risk per trade.
   * Positive expectancy is required for a model to pass validation gates.
   * Stored as NUMERIC(10,4); NULL when expectancy could not be computed.
   */
  @Column({ type: 'decimal', precision: 10, scale: 4, nullable: true })
  expectancy!: string | null;

  /**
   * Win rate expressed as a percentage (0.00–100.00).
   * Stored as NUMERIC(5,2); NULL when win rate could not be computed.
   */
  @Column({ type: 'decimal', precision: 5, scale: 2, nullable: true })
  win_rate!: string | null;

  /**
   * Maximum peak-to-trough drawdown expressed as a fraction (0.0000–1.0000).
   * Lower values indicate better capital preservation.
   * Stored as NUMERIC(8,4); NULL when drawdown could not be computed.
   */
  @Column({ type: 'decimal', precision: 8, scale: 4, nullable: true })
  max_drawdown!: string | null;

  /**
   * TRUE when this evaluation run passed all configured validation gates.
   * FALSE when one or more gates failed; see failure_reason for detail.
   */
  @Column({ type: 'boolean' })
  passed_all_gates!: boolean;

  /**
   * Human-readable description of the first gate that failed validation.
   * NULL when passed_all_gates is TRUE.
   */
  @Column({ type: 'text', nullable: true })
  failure_reason!: string | null;

  /** Row creation timestamp (UTC); set once by the database on INSERT. */
  @CreateDateColumn({ type: 'timestamptz' })
  created_at!: Date;
}
