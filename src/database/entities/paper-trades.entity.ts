/**
 * PaperTrades entity — isolated paper-trading mirror of the Trades table.
 *
 * Stored in `paper_trades` to guarantee zero overlap with the live `trades`
 * table (Requirement 10.1: no shared database tables between PaperEngine and
 * LiveEngine).
 *
 * Implements append-only semantics: no record is modified or deleted after
 * initial creation.  Simulated P&L fields use the same cost formulas as the
 * LiveEngine (Requirement 10.6).
 *
 * Requirements: 10.1, 10.6
 */

import {
  Entity,
  PrimaryGeneratedColumn,
  Column,
  CreateDateColumn,
  ManyToOne,
  JoinColumn,
  Index,
} from 'typeorm';
import { PaperPosition } from './paper-positions.entity';

/** Exit timing classification relative to the trade's MFE. */
export type PaperExitClassification =
  'premature' | 'near-optimal' | 'late' | 'no-favorable-excursion';

/** Composite execution quality grade for paper simulated fills. */
export type PaperExecutionQuality =
  'Poor' | 'Fair' | 'Good' | 'Excellent' | 'No Favorable Excursion';

@Entity('paper_trades')
@Index('idx_paper_trades_entry_time', ['entry_time'])
@Index('idx_paper_trades_strategy_entry_time', ['strategy_id', 'entry_time'])
export class PaperTrade {
  /** UUID primary key — generated by TypeORM (uuid v4). */
  @PrimaryGeneratedColumn('uuid')
  id!: string;

  /**
   * Engine identifier — always 'PAPER' for this table.
   * Retained to mirror the Trades schema.
   */
  @Column({ type: 'varchar', length: 10, default: 'PAPER' })
  engine!: string;

  /**
   * FK → paper_positions.id — the paper position this trade closes (or
   * partially closes). Stored as both a plain column and a typed relation.
   */
  @Column({ name: 'position_id', type: 'uuid' })
  position_id!: string;

  @ManyToOne(() => PaperPosition, (position) => position.trades, {
    nullable: false,
    onDelete: 'RESTRICT',
  })
  @JoinColumn({ name: 'position_id' })
  position!: PaperPosition;

  /** FK → instruments.id — the instrument traded. */
  @Column({ name: 'instrument_id', type: 'uuid' })
  instrument_id!: string;

  /**
   * FK → strategies.id — the strategy that generated the entry signal.
   * NULL for paper trades without a strategy context.
   */
  @Column({ name: 'strategy_id', type: 'uuid', nullable: true })
  strategy_id!: string | null;

  /**
   * FK → signals.id — the signal that initiated entry.
   * NULL for manually triggered paper trades.
   */
  @Column({ name: 'signal_id', type: 'uuid', nullable: true })
  signal_id!: string | null;

  /** Trade direction. */
  @Column({ type: 'varchar', length: 5 })
  direction!: string; // 'LONG' | 'SHORT'

  /** Total quantity (in units, not lots) for this paper trade record. */
  @Column({ type: 'integer' })
  quantity!: number;

  /**
   * Contract lot size at the time of the trade.
   * Captured at trade time because NSE lot sizes can change on expiry roll.
   */
  @Column({ name: 'lot_size', type: 'integer', default: 1 })
  lot_size!: number;

  /** Volume-weighted average entry price (NUMERIC 12,2). */
  @Column({ name: 'entry_price', type: 'numeric', precision: 12, scale: 2 })
  entry_price!: string;

  /** Volume-weighted average exit price (NUMERIC 12,2). */
  @Column({ name: 'exit_price', type: 'numeric', precision: 12, scale: 2 })
  exit_price!: string;

  /** UTC timestamp of the first entry execution. */
  @Column({ name: 'entry_time', type: 'timestamptz' })
  entry_time!: Date;

  /** UTC timestamp of the final exit execution. */
  @Column({ name: 'exit_time', type: 'timestamptz' })
  exit_time!: Date;

  /**
   * Maximum Favorable Excursion for this paper trade (NUMERIC 15,2).
   * Copied from the parent PaperPosition at trade close time.
   */
  @Column({ type: 'numeric', precision: 15, scale: 2, default: '0' })
  mfe!: string;

  /**
   * Maximum Adverse Excursion for this paper trade (NUMERIC 15,2).
   * Copied from the parent PaperPosition at trade close time.
   */
  @Column({ type: 'numeric', precision: 15, scale: 2, default: '0' })
  mae!: string;

  // ── P&L components ─────────────────────────────────────────────────────────

  /**
   * Gross P&L before any costs (NUMERIC 15,2).
   * LONG: (exit_price − entry_price) × quantity.
   * SHORT: (entry_price − exit_price) × quantity.
   */
  @Column({ name: 'gross_pnl', type: 'numeric', precision: 15, scale: 2 })
  gross_pnl!: string;

  /** Simulated broker brokerage charge (NUMERIC 10,4). */
  @Column({ type: 'numeric', precision: 10, scale: 4 })
  brokerage!: string;

  /** Simulated Securities Transaction Tax (NUMERIC 10,4). */
  @Column({ type: 'numeric', precision: 10, scale: 4 })
  stt!: string;

  /** Simulated NSE exchange transaction charge (NUMERIC 10,4). */
  @Column({ name: 'exchange_charges', type: 'numeric', precision: 10, scale: 4 })
  exchange_charges!: string;

  /** Simulated Goods and Services Tax on brokerage + exchange charges (NUMERIC 10,4). */
  @Column({ type: 'numeric', precision: 10, scale: 4 })
  gst!: string;

  /** Simulated SEBI regulatory fee (NUMERIC 10,4). */
  @Column({ name: 'sebi_charges', type: 'numeric', precision: 10, scale: 4 })
  sebi_charges!: string;

  /** Simulated state-level stamp duty (NUMERIC 10,4). */
  @Column({ name: 'stamp_duty', type: 'numeric', precision: 10, scale: 4 })
  stamp_duty!: string;

  /**
   * Net P&L after all simulated costs (NUMERIC 15,2).
   * gross_pnl − (brokerage + stt + exchange_charges + gst + sebi_charges + stamp_duty).
   * Used by PaperTradingService to update `paper:portfolio:balance`.
   */
  @Column({ name: 'net_pnl', type: 'numeric', precision: 15, scale: 2 })
  net_pnl!: string;

  // ── Metadata & quality metrics ─────────────────────────────────────────────

  /** Human-readable reason for the exit (e.g. 'SL_HIT', 'TARGET_HIT', 'MANUAL'). */
  @Column({ name: 'exit_reason', type: 'varchar' })
  exit_reason!: string;

  /**
   * Observed total simulated execution slippage (NUMERIC 10,4).
   * Sum of entry and exit fill slippages.
   */
  @Column({ name: 'execution_slippage', type: 'numeric', precision: 10, scale: 4, default: '0' })
  execution_slippage!: string;

  /**
   * Composite signal score at entry time (NUMERIC 5,2).
   * NULL for paper trades entered without a scored signal.
   */
  @Column({ name: 'signal_score', type: 'numeric', precision: 5, scale: 2, nullable: true })
  signal_score!: string | null;

  /**
   * Dhan entry order ID — always NULL for paper trades.
   * Column retained to mirror the Trades schema.
   */
  @Column({ name: 'dhan_entry_order_id', type: 'varchar', nullable: true })
  dhan_entry_order_id!: string | null;

  /**
   * Dhan exit order ID — always NULL for paper trades.
   * Column retained to mirror the Trades schema.
   */
  @Column({ name: 'dhan_exit_order_id', type: 'varchar', nullable: true })
  dhan_exit_order_id!: string | null;

  /**
   * Quality-to-Cost Ratio (NUMERIC 8,4).
   * net_pnl / (total_transaction_costs + |execution_slippage|).
   * NULL when costs + slippage = 0.
   */
  @Column({ type: 'numeric', precision: 8, scale: 4, nullable: true })
  qcr!: string | null;

  /**
   * Qualitative assessment of exit timing relative to MFE.
   * NULL until classification runs post-close.
   */
  @Column({ name: 'exit_classification', type: 'varchar', nullable: true })
  exit_classification!: PaperExitClassification | null;

  /**
   * Composite execution quality grade for simulated fills.
   * NULL until quality scoring runs post-close.
   */
  @Column({ name: 'execution_quality', type: 'varchar', nullable: true })
  execution_quality!: PaperExecutionQuality | null;

  /** UTC timestamp when the row was first inserted. */
  @CreateDateColumn({ name: 'created_at', type: 'timestamptz' })
  created_at!: Date;
}
