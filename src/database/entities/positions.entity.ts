/**
 * Positions entity — represents a live or historical directional position in a
 * single instrument, aggregated across all entry executions.
 *
 * MFE (Maximum Favorable Excursion) and MAE (Maximum Adverse Excursion) are
 * updated continuously by PositionMonitoringModule from tick data.
 *
 * Requirements: 18.1 (schema)
 *
 * NUMERIC columns are typed as `string` because PostgreSQL NUMERIC can exceed
 * IEEE-754 double precision; TypeORM/pg returns them as strings by default.
 *
 * `!` definite-assignment assertions are used on all ORM-populated properties
 * because TypeORM hydrates instances at runtime, not via constructors.
 */

import {
  Entity,
  PrimaryGeneratedColumn,
  Column,
  CreateDateColumn,
  UpdateDateColumn,
  Index,
  OneToMany,
} from 'typeorm';
import { Trade } from './trades.entity';

/** Position direction — determines SL monotonicity direction. */
export type Direction = 'LONG' | 'SHORT';

@Entity('positions')
@Index('idx_positions_engine_is_open', ['engine', 'is_open'])
@Index('idx_positions_instrument_is_open', ['instrument_id', 'is_open'])
export class Position {
  /** UUID primary key — generated by TypeORM (uuid v4). */
  @PrimaryGeneratedColumn('uuid')
  id!: string;

  /** Execution engine that owns this position — strictly isolated. */
  @Column({ type: 'varchar', length: 10 })
  engine!: string; // 'LIVE' | 'PAPER'

  /** FK → instruments.id — the instrument held. */
  @Column({ name: 'instrument_id', type: 'uuid' })
  instrument_id!: string;

  /**
   * FK → signals.id — the signal that initiated this position.
   * NULL for positions opened via manual intervention or system-triggered entries
   * that bypass the signal pipeline.
   */
  @Column({ name: 'signal_id', type: 'uuid', nullable: true })
  signal_id!: string | null;

  /** Trade direction; determines SL monotonicity rules enforced by TrailingStopEngine. */
  @Column({ type: 'varchar', length: 5 })
  direction!: Direction;

  /** Current open quantity (decreases on partial exits). */
  @Column({ type: 'integer' })
  quantity!: number;

  /**
   * Volume-weighted average price of all entry executions (NUMERIC 12,2).
   * Recalculated on each additional entry for scaled-in positions.
   */
  @Column({ name: 'average_entry_price', type: 'numeric', precision: 12, scale: 2 })
  average_entry_price!: string;

  /**
   * Active stop-loss level (NUMERIC 12,2).
   * Monotonically moves in the profit direction only (enforced by TrailingStopEngine).
   * NULL until the first trailing stop activation.
   */
  @Column({ name: 'current_sl', type: 'numeric', precision: 12, scale: 2, nullable: true })
  current_sl!: string | null;

  /**
   * Target price for this position leg (NUMERIC 12,2).
   * NULL when the strategy has no fixed target (trailing-stop-only exits).
   */
  @Column({ name: 'target_price', type: 'numeric', precision: 12, scale: 2, nullable: true })
  target_price!: string | null;

  /**
   * Name of the active trailing stop mechanism (e.g. 'ATR', 'CHANDELIER',
   * 'PERCENTAGE', 'SWING_HL', 'VOLATILITY_ADJUSTED', 'STRUCTURE', 'TIME',
   * 'PARTIAL_PROFIT').  NULL before TrailingStopEngine activates.
   */
  @Column({ name: 'trailing_stop_mechanism', type: 'varchar', nullable: true })
  trailing_stop_mechanism!: string | null;

  /**
   * Real-time unrealized P&L computed from current mark price (NUMERIC 15,2).
   * Continuously updated by PositionMonitoringModule; fed to RiskEngine for
   * EMERGENCY_HALT threshold monitoring.
   */
  @Column({
    name: 'unrealized_pnl',
    type: 'numeric',
    precision: 15,
    scale: 2,
    default: '0',
  })
  unrealized_pnl!: string;

  /**
   * Maximum Favorable Excursion — highest unrealized P&L reached since entry
   * (NUMERIC 15,2).  Updated only when current unrealized_pnl > stored mfe.
   */
  @Column({ type: 'numeric', precision: 15, scale: 2, default: '0' })
  mfe!: string;

  /**
   * Maximum Adverse Excursion — most negative unrealized P&L reached since entry
   * (NUMERIC 15,2).  Updated only when current unrealized_pnl < stored mae.
   */
  @Column({ type: 'numeric', precision: 15, scale: 2, default: '0' })
  mae!: string;

  /** UTC timestamp when the first entry execution was confirmed. */
  @Column({ name: 'opened_at', type: 'timestamptz' })
  opened_at!: Date;

  /**
   * UTC timestamp when the position was fully closed.
   * NULL for open positions; set by ExecutionService on the final exit fill.
   */
  @Column({ name: 'closed_at', type: 'timestamptz', nullable: true })
  closed_at!: Date | null;

  /**
   * Boolean flag for fast open-position queries.
   * Set to `false` by ExecutionService when quantity reaches 0.
   * Indexed together with `engine` and `instrument_id`.
   */
  @Column({ name: 'is_open', type: 'boolean', default: true })
  is_open!: boolean;

  /** UTC timestamp when the row was first inserted. */
  @CreateDateColumn({ name: 'created_at', type: 'timestamptz' })
  created_at!: Date;

  /** UTC timestamp of the most recent update to this row. */
  @UpdateDateColumn({ name: 'updated_at', type: 'timestamptz' })
  updated_at!: Date;

  // ── Relations ──────────────────────────────────────────────────────────────

  /**
   * Completed trade records derived from this position.
   * Inverse side of Trade.position.
   */
  @OneToMany(() => Trade, (trade) => trade.position)
  trades!: Trade[];
}
