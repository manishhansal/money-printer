/**
 * MarketSnapshots entity — captures a point-in-time snapshot of live market
 * data for a given instrument, including LTP, OHLC, volume, OI, and best
 * bid/ask depth.
 *
 * High-frequency write path: one row is inserted per instrument per tick during
 * market hours.  The compound index on (instrument_id, snapshot_at DESC)
 * supports efficient "latest-N snapshots for an instrument" queries.
 *
 * All price/financial columns use NUMERIC to avoid floating-point precision
 * loss.  Timestamps are stored in UTC (timestamp with time zone).
 *
 * The `!` definite assignment assertions tell TypeScript that TypeORM will
 * populate these properties at runtime (via hydration), not the constructor.
 *
 * Requirements: 18.1, 18.8
 */

import { Column, Entity, Index, PrimaryGeneratedColumn } from 'typeorm';

/**
 * Compound index supporting efficient range queries ordered by recency.
 * NOTE: The migration for this index MUST specify `snapshot_at DESC` so that
 * "latest snapshot" queries avoid a sort step.
 *
 * SQL equivalent:
 *   CREATE INDEX "IDX_market_snapshots_instrument_snapshot_at"
 *     ON market_snapshots (instrument_id, snapshot_at DESC);
 */
@Entity({ name: 'market_snapshots' })
@Index('IDX_market_snapshots_instrument_snapshot_at', ['instrumentId', 'snapshotAt'])
export class MarketSnapshots {
  /** UUID primary key — generated by TypeORM (uuid package). */
  @PrimaryGeneratedColumn('uuid')
  id!: string;

  /**
   * References the instrument this snapshot belongs to.
   * FK → instruments.id.
   *
   * Stored as a plain uuid column; the @ManyToOne relation decorators are
   * defined on the Instruments entity (task 2.1).
   */
  @Column({ name: 'instrument_id', type: 'uuid' })
  instrumentId!: string;

  /**
   * Last traded price at the time of the snapshot.
   * NUMERIC(12,2) — supports up to ₹9,999,999,999.99.
   * TypeORM/pg returns NUMERIC as string; callers must parse for arithmetic.
   */
  @Column({ name: 'ltp', type: 'numeric', precision: 12, scale: 2 })
  ltp!: string;

  /**
   * Opening price for the current session.
   * NUMERIC(12,2).
   */
  @Column({ name: 'open_price', type: 'numeric', precision: 12, scale: 2 })
  openPrice!: string;

  /**
   * Intraday high price at the time of the snapshot.
   * NUMERIC(12,2).
   */
  @Column({ name: 'high_price', type: 'numeric', precision: 12, scale: 2 })
  highPrice!: string;

  /**
   * Intraday low price at the time of the snapshot.
   * NUMERIC(12,2).
   */
  @Column({ name: 'low_price', type: 'numeric', precision: 12, scale: 2 })
  lowPrice!: string;

  /**
   * Closing / previous-close price used as reference.
   * NUMERIC(12,2).
   */
  @Column({ name: 'close_price', type: 'numeric', precision: 12, scale: 2 })
  closePrice!: string;

  /**
   * Traded volume at the time of the snapshot.
   * BIGINT — TypeORM returns bigint columns as string in JavaScript to
   * avoid 53-bit integer precision loss.
   */
  @Column({ name: 'volume', type: 'bigint' })
  volume!: string;

  /**
   * Open interest at the time of the snapshot.
   * Nullable — not available for all instrument types (e.g. equities).
   * BIGINT returned as string.
   */
  @Column({ name: 'oi', type: 'bigint', nullable: true })
  oi!: string | null;

  /**
   * Best bid price at the time of the snapshot.
   * Nullable — depth data may not always be available.
   * NUMERIC(12,2).
   */
  @Column({
    name: 'bid_price',
    type: 'numeric',
    precision: 12,
    scale: 2,
    nullable: true,
  })
  bidPrice!: string | null;

  /**
   * Best ask price at the time of the snapshot.
   * Nullable — depth data may not always be available.
   * NUMERIC(12,2).
   */
  @Column({
    name: 'ask_price',
    type: 'numeric',
    precision: 12,
    scale: 2,
    nullable: true,
  })
  askPrice!: string | null;

  /**
   * Quantity available at the best bid.
   * Nullable — depth data may not always be available.
   */
  @Column({ name: 'bid_qty', type: 'integer', nullable: true })
  bidQty!: number | null;

  /**
   * Quantity available at the best ask.
   * Nullable — depth data may not always be available.
   */
  @Column({ name: 'ask_qty', type: 'integer', nullable: true })
  askQty!: number | null;

  /**
   * UTC timestamp at which this market snapshot was captured.
   * The compound index uses this column in DESC order (see class decorator).
   */
  @Column({ name: 'snapshot_at', type: 'timestamp with time zone' })
  snapshotAt!: Date;
}
