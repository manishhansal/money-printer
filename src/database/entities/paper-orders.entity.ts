/**
 * PaperOrders entity — isolated paper-trading mirror of the Orders table.
 *
 * Stored in `paper_orders` to guarantee zero overlap with the live `orders`
 * table (Requirement 10.1: no shared database tables between PaperEngine and
 * LiveEngine).
 *
 * Structure mirrors orders.entity.ts exactly; `dhan_order_id` and
 * `dhan_correlation_id` are always NULL for paper orders because simulated
 * fills never reach the Dhan broker.
 *
 * Requirements: 10.1
 */

import {
  Entity,
  PrimaryGeneratedColumn,
  Column,
  CreateDateColumn,
  UpdateDateColumn,
  Index,
  OneToMany,
} from 'typeorm';
import { PaperExecution } from './paper-executions.entity';

/** Order type classification. */
export type PaperOrderType = 'MARKET' | 'LIMIT' | 'SL' | 'SL-M';

/** Transaction direction. */
export type PaperTransactionType = 'BUY' | 'SELL';

/** Full set of lifecycle statuses a paper order can occupy. */
export type PaperOrderStatus =
  'pending' | 'submitted' | 'open' | 'partial' | 'complete' | 'cancelled' | 'rejected';

@Entity('paper_orders')
@Index('idx_paper_orders_instrument_status', ['instrument_id', 'status'])
@Index('idx_paper_orders_created_at', ['created_at'])
export class PaperOrder {
  /** UUID primary key — generated by TypeORM (uuid v4). */
  @PrimaryGeneratedColumn('uuid')
  id!: string;

  /**
   * Client-assigned idempotency key (UUID).
   * Stored in Redis with 5-minute TTL (key: `paper:orders:idempotency:{key}`) to
   * prevent duplicate submissions (mirrors live engine idempotency pattern).
   */
  @Column({ name: 'idempotency_key', type: 'varchar', length: 100, unique: true })
  idempotency_key!: string;

  /**
   * Engine identifier — always 'PAPER' for this table.
   * Retained to mirror the Orders schema and support audit queries.
   */
  @Column({ type: 'varchar', length: 10, default: 'PAPER' })
  engine!: string;

  /**
   * FK → signals.id — the signal that triggered this order.
   * Nullable: system-level paper orders have no signal.
   */
  @Column({ name: 'signal_id', type: 'uuid', nullable: true })
  signal_id!: string | null;

  /** FK → instruments.id — the tradable instrument for this paper order. */
  @Column({ name: 'instrument_id', type: 'uuid' })
  instrument_id!: string;

  /** Order variety (MARKET, LIMIT, SL, SL-M). */
  @Column({ name: 'order_type', type: 'varchar', length: 10 })
  order_type!: PaperOrderType;

  /** Direction of the order leg. */
  @Column({ name: 'transaction_type', type: 'varchar', length: 4 })
  transaction_type!: PaperTransactionType;

  /** Number of lots/units ordered. */
  @Column({ type: 'integer' })
  quantity!: number;

  /**
   * Limit price for LIMIT orders (NUMERIC 12,2).
   * NULL for MARKET orders.
   */
  @Column({ type: 'numeric', precision: 12, scale: 2, nullable: true })
  price!: string | null;

  /**
   * Trigger price for SL / SL-M orders (NUMERIC 12,2).
   * NULL for MARKET and LIMIT orders.
   */
  @Column({ name: 'trigger_price', type: 'numeric', precision: 12, scale: 2, nullable: true })
  trigger_price!: string | null;

  /**
   * Dhan platform order ID — always NULL for paper orders (no broker submission).
   * Column retained to mirror the Orders schema.
   */
  @Column({ name: 'dhan_order_id', type: 'varchar', nullable: true })
  dhan_order_id!: string | null;

  /**
   * Dhan correlation ID — always NULL for paper orders.
   * Column retained to mirror the Orders schema.
   */
  @Column({ name: 'dhan_correlation_id', type: 'varchar', nullable: true })
  dhan_correlation_id!: string | null;

  /** Current lifecycle status of this paper order. */
  @Column({ type: 'varchar', length: 20 })
  status!: PaperOrderStatus;

  /** Rejection reason when status is 'rejected'. */
  @Column({ name: 'rejection_reason', type: 'text', nullable: true })
  rejection_reason!: string | null;

  /** UTC timestamp when the simulated submission was processed. */
  @Column({ name: 'submitted_at', type: 'timestamptz', nullable: true })
  submitted_at!: Date | null;

  /** Cumulative quantity filled so far (for partial fills). */
  @Column({ name: 'filled_quantity', type: 'integer', default: 0 })
  filled_quantity!: number;

  /**
   * Volume-weighted average fill price across all paper executions (NUMERIC 12,2).
   * NULL until at least one paper execution has been recorded.
   */
  @Column({
    name: 'average_fill_price',
    type: 'numeric',
    precision: 12,
    scale: 2,
    nullable: true,
  })
  average_fill_price!: string | null;

  /** UTC timestamp when the row was first inserted. */
  @CreateDateColumn({ name: 'created_at', type: 'timestamptz' })
  created_at!: Date;

  /** UTC timestamp of the most recent update to this row. */
  @UpdateDateColumn({ name: 'updated_at', type: 'timestamptz' })
  updated_at!: Date;

  // ── Relations ──────────────────────────────────────────────────────────────

  /**
   * One paper order may produce multiple partial paper executions (fills).
   * Inverse side of PaperExecution.order.
   */
  @OneToMany(() => PaperExecution, (execution) => execution.order)
  executions!: PaperExecution[];
}
