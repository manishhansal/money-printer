/**
 * Orders entity — tracks every order submission through its full lifecycle.
 *
 * Requirements: 16.6 (idempotency key), 18.1 (schema)
 *
 * NUMERIC columns are typed as `string` because PostgreSQL NUMERIC can exceed
 * IEEE-754 double precision; TypeORM/pg returns them as strings by default.
 *
 * `!` definite-assignment assertions are used on all ORM-populated properties
 * because TypeORM hydrates instances at runtime, not via constructors.
 */

import {
  Entity,
  PrimaryGeneratedColumn,
  Column,
  CreateDateColumn,
  UpdateDateColumn,
  Index,
  OneToMany,
} from 'typeorm';
import { Execution } from './executions.entity';

/** Valid engine identifiers shared across trading entities. */
export type Engine = 'LIVE' | 'PAPER';

/** Order type classification. */
export type OrderType = 'MARKET' | 'LIMIT' | 'SL' | 'SL-M';

/** Transaction direction. */
export type TransactionType = 'BUY' | 'SELL';

/** Full set of lifecycle statuses an order can occupy. */
export type OrderStatus =
  'pending' | 'submitted' | 'open' | 'partial' | 'complete' | 'cancelled' | 'rejected';

@Entity('orders')
@Index('idx_orders_instrument_status', ['instrument_id', 'status'])
@Index('idx_orders_engine_created_at', ['engine', 'created_at'])
export class Order {
  /** UUID primary key — generated by TypeORM (uuid v4). */
  @PrimaryGeneratedColumn('uuid')
  id!: string;

  /**
   * Client-assigned idempotency key (UUID).
   * Stored in Redis with 5-minute TTL (key: `orders:idempotency:{key}`) to
   * prevent duplicate submissions to the broker (Requirement 16.6).
   */
  @Column({ name: 'idempotency_key', type: 'varchar', length: 100, unique: true })
  idempotency_key!: string;

  /** Execution engine that owns this order — strictly isolated. */
  @Column({ type: 'varchar', length: 10 })
  engine!: Engine;

  /**
   * FK → signals.id — the signal that triggered this order.
   * Nullable: system-level orders (e.g. mandatory square-off) have no signal.
   */
  @Column({ name: 'signal_id', type: 'uuid', nullable: true })
  signal_id!: string | null;

  /** FK → instruments.id — the tradable instrument for this order. */
  @Column({ name: 'instrument_id', type: 'uuid' })
  instrument_id!: string;

  /** Order variety (MARKET, LIMIT, SL, SL-M). */
  @Column({ name: 'order_type', type: 'varchar', length: 10 })
  order_type!: OrderType;

  /** Direction of the order leg. */
  @Column({ name: 'transaction_type', type: 'varchar', length: 4 })
  transaction_type!: TransactionType;

  /** Number of lots/units ordered. */
  @Column({ type: 'integer' })
  quantity!: number;

  /**
   * Limit price for LIMIT orders (NUMERIC 12,2).
   * NULL for MARKET orders.
   */
  @Column({ type: 'numeric', precision: 12, scale: 2, nullable: true })
  price!: string | null;

  /**
   * Trigger price for SL / SL-M orders (NUMERIC 12,2).
   * NULL for MARKET and LIMIT orders.
   */
  @Column({ name: 'trigger_price', type: 'numeric', precision: 12, scale: 2, nullable: true })
  trigger_price!: string | null;

  /** Dhan platform order ID returned on submission — NULL until submitted. */
  @Column({ name: 'dhan_order_id', type: 'varchar', nullable: true })
  dhan_order_id!: string | null;

  /** Dhan correlation ID for tracking through WebSocket feed updates. */
  @Column({ name: 'dhan_correlation_id', type: 'varchar', nullable: true })
  dhan_correlation_id!: string | null;

  /** Current lifecycle status of this order. */
  @Column({ type: 'varchar', length: 20 })
  status!: OrderStatus;

  /** Human-readable reason provided by the broker on rejection. */
  @Column({ name: 'rejection_reason', type: 'text', nullable: true })
  rejection_reason!: string | null;

  /** UTC timestamp when the order was forwarded to the broker. */
  @Column({ name: 'submitted_at', type: 'timestamptz', nullable: true })
  submitted_at!: Date | null;

  /** Cumulative quantity filled so far (for partial fills). */
  @Column({ name: 'filled_quantity', type: 'integer', default: 0 })
  filled_quantity!: number;

  /**
   * Volume-weighted average fill price across all executions (NUMERIC 12,2).
   * NULL until at least one execution has been recorded.
   */
  @Column({
    name: 'average_fill_price',
    type: 'numeric',
    precision: 12,
    scale: 2,
    nullable: true,
  })
  average_fill_price!: string | null;

  /** UTC timestamp when the row was first inserted. */
  @CreateDateColumn({ name: 'created_at', type: 'timestamptz' })
  created_at!: Date;

  /** UTC timestamp of the most recent update to this row. */
  @UpdateDateColumn({ name: 'updated_at', type: 'timestamptz' })
  updated_at!: Date;

  // ── Relations ──────────────────────────────────────────────────────────────

  /**
   * One order may produce multiple partial executions (fills).
   * Inverse side of Execution.order.
   */
  @OneToMany(() => Execution, (execution) => execution.order)
  executions!: Execution[];
}
